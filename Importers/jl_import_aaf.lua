aaf.SPEC_CLASSES = SPEC_CLASSES

local function fail(fmt, ...)
  error("aaf: " .. string.format(fmt, ...), 0)
end

local function hex(s)
  return (s:gsub(".", function(c) return string.format("%02x", c:byte()) end))
end
aaf.hex = hex

-- A UTF-16 null-terminated string in the given byte order ("<" or ">").
local function utf16_string(bytes, bo)
  if bo == ">" then
    bytes = bytes:gsub("(.)(.)", "%2%1")
  end
  local s = cfb.utf16le_to_utf8(bytes)
  local z = s:find("\0", 1, true)
  if z then s = s:sub(1, z - 1) end
  return s
end

-- A sequence of null-terminated UTF-16 strings (MS-01 StringArray).
local function utf16_string_array(bytes, bo)
  local out = {}
  local start = 1
  for i = 1, #bytes - 1, 2 do
    if bytes:byte(i) == 0 and bytes:byte(i + 1) == 0 then
      out[#out + 1] = utf16_string(bytes:sub(start, i - 1), bo)
      start = i + 2
    end
  end
  return out
end

-- AUIDs are compared and used as table keys in the byte layout of a storage
-- CLSID ([MS-CFB] 2.6.1, little-endian GUID). MS-01's AUID is a record of
-- UInt32, UInt16, UInt16 and 8 bytes, so a value from a big-endian property
-- stream has its first three fields swapped back.
local function auid_key(bytes, bo)
  if bo ~= ">" or #bytes ~= 16 then return bytes end
  local d1, d2, d3 = string.unpack(">I4I2I2", bytes)
  return string.pack("<I4I2I2", d1, d2, d3) .. bytes:sub(9)
end
aaf.auid_key = auid_key

-- Display form of an AUID key: the usual GUID text layout.
function aaf.auid_string(key)
  if #key ~= 16 then return hex(key) end
  local d1, d2, d3 = string.unpack("<I4I2I2", key)
  return string.format("%08x-%04x-%04x-%s-%s", d1, d2, d3, hex(key:sub(9, 10)), hex(key:sub(11, 16)))
end

