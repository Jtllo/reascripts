-- cfb.lua: layer 1 of jl_import_aaf, a reader for the Compound File Binary
-- File Format, the container AAF files are stored in.
--
-- Source: Microsoft, [MS-CFB] Compound File Binary File Format, v20240423
-- (protocol revision 12.0). Section numbers below refer to that document.
--
-- Read-only. Large streams are never read whole: callers ask for byte ranges
-- (read) or iterate fixed-size chunks (chunks). Pure Lua 5.3/5.4.

local cfb = {}

-- [MS-CFB] 2.1: reserved sector numbers.
local MAXREGSECT = 0xFFFFFFFA
local ENDOFCHAIN = 0xFFFFFFFE
local FREESECT   = 0xFFFFFFFF

-- [MS-CFB] 2.6.1: stream IDs.
local MAXREGSID = 0xFFFFFFFA
local NOSTREAM  = 0xFFFFFFFF

-- [MS-CFB] 2.2: header signature.
local SIGNATURE = "\xD0\xCF\x11\xE0\xA1\xB1\x1A\xE1"
-- [MS-CFB] 2.2: the header structure itself is 512 bytes in both versions.
local HEADER_SIZE = 512
-- [MS-CFB] 2.2: the header holds the first 109 DIFAT entries.
local HEADER_DIFAT_COUNT = 109
-- [MS-CFB] 2.6.1: directory entries are 128 bytes.
local DIR_ENTRY_SIZE = 128

-- [MS-CFB] 2.6.1, Object Type.
local OBJECT_TYPES = {
  [0x00] = "unknown",
  [0x01] = "storage",
  [0x02] = "stream",
  [0x05] = "root",
}

cfb.ENDOFCHAIN = ENDOFCHAIN
cfb.NOSTREAM = NOSTREAM

local function fail(fmt, ...)
  error("cfb: " .. string.format(fmt, ...), 0)
end

-- UTF-16LE code units to UTF-8, pairing surrogates. An unpaired surrogate
-- becomes U+FFFD rather than an error: names are for display and lookup.
local function utf16le_to_utf8(s)
  local out = {}
  local i, n = 1, #s - 1
  while i <= n do
    local u = string.unpack("<I2", s, i)
    i = i + 2
    if u >= 0xD800 and u <= 0xDBFF and i <= n then
      local lo = string.unpack("<I2", s, i)
      if lo >= 0xDC00 and lo <= 0xDFFF then
        u = 0x10000 + ((u - 0xD800) << 10) + (lo - 0xDC00)
        i = i + 2
      else
        u = 0xFFFD
      end
    elseif u >= 0xD800 and u <= 0xDFFF then
      u = 0xFFFD
    end
    out[#out + 1] = utf8.char(u)
  end
  return table.concat(out)
end
cfb.utf16le_to_utf8 = utf16le_to_utf8

local Doc = {}
Doc.__index = Doc

function Doc:_read_at(offset, length)
  local ok = self.fh:seek("set", offset)
  if not ok then fail("seek to %d failed", offset) end
  local data = self.fh:read(length)
  if data == nil or #data ~= length then
    fail("short read at offset %d (wanted %d bytes)", offset, length)
  end
  return data
end

-- [MS-CFB] 2.3: sector N begins at byte offset (N + 1) x Sector Size.
function Doc:_sector_offset(sector)
  return (sector + 1) * self.sector_size
end

function Doc:_read_sector(sector)
  if sector > MAXREGSECT then fail("invalid sector number 0x%08X", sector) end
  return self:_read_at(self:_sector_offset(sector), self.sector_size)
end

-- Unpack a whole sector of 32-bit little-endian integers into a 0-based
-- table appended at `base`.
local function unpack_u32_array(data, count, dest, base)
  local fmt = "<" .. string.rep("I4", count)
  local vals = table.pack(string.unpack(fmt, data))
  for k = 1, count do dest[base + k - 1] = vals[k] end
end

-- [MS-CFB] 2.2 header, 2.5 DIFAT, 2.3 FAT.
function Doc:_load_header_and_fat()
  local h = self:_read_at(0, HEADER_SIZE)
  if h:sub(1, 8) ~= SIGNATURE then fail("not a compound file (bad signature)") end

  -- [MS-CFB] 2.2 field layout, offsets from the start of the file.
  local minor, major, byte_order, sector_shift, mini_shift =
    string.unpack("<I2I2I2I2I2", h, 25)
  local n_dir_sectors, n_fat_sectors, first_dir, _txn, mini_cutoff,
        first_minifat, n_minifat, first_difat, n_difat =
    string.unpack("<I4I4I4I4I4I4I4I4I4", h, 41)

  if byte_order ~= 0xFFFE then fail("bad byte order mark 0x%04X", byte_order) end
  -- [MS-CFB] 2.2 Sector Shift: 9 (512 bytes) for version 3, 12 (4096) for 4.
  if not ((major == 3 and sector_shift == 9) or (major == 4 and sector_shift == 12)) then
    fail("unsupported version %d with sector shift %d", major, sector_shift)
  end
  -- [MS-CFB] 2.2 Mini Sector Shift MUST be 6 (64-byte mini sectors).
  if mini_shift ~= 6 then fail("unsupported mini sector shift %d", mini_shift) end

  self.minor_version = minor
  self.major_version = major
  self.sector_size = 1 << sector_shift
  self.mini_sector_size = 1 << mini_shift
  -- [MS-CFB] 2.2 Mini Stream Cutoff Size, 4096 by the spec; honour the field.
  self.mini_cutoff = mini_cutoff
  self.first_dir_sector = first_dir
  self.n_dir_sectors = n_dir_sectors
  self.first_minifat_sector = first_minifat
  self.n_minifat_sectors = n_minifat

  -- [MS-CFB] 2.5: the DIFAT lists the FAT sectors in order; 109 entries in
  -- the header, then (sector size / 4 - 1) per DIFAT sector, whose last field
  -- is the next DIFAT sector.
  local difat = {}
  local header_difat = table.pack(string.unpack("<" .. string.rep("I4", HEADER_DIFAT_COUNT), h, 77))
  for k = 1, HEADER_DIFAT_COUNT do difat[#difat + 1] = header_difat[k] end

  local per_difat_sector = self.sector_size // 4 - 1
  local ds = first_difat
  local seen = 0
  while ds ~= ENDOFCHAIN and ds ~= FREESECT and seen < n_difat do
    local data = self:_read_sector(ds)
    local vals = table.pack(string.unpack("<" .. string.rep("I4", per_difat_sector + 1), data))
    for k = 1, per_difat_sector do difat[#difat + 1] = vals[k] end
    ds = vals[per_difat_sector + 1]
    seen = seen + 1
  end
  if seen < n_difat then fail("DIFAT chain ended after %d of %d sectors", seen, n_difat) end

  -- [MS-CFB] 2.3: the FAT is the concatenation of the FAT sectors named by the
  -- DIFAT, taken as one array of next-sector numbers (0-based here).
  local fat = {}
  local per_sector = self.sector_size // 4
  for i = 1, n_fat_sectors do
    local fs = difat[i]
    if fs == nil or fs > MAXREGSECT then
      fail("DIFAT entry %d does not name a FAT sector", i - 1)
    end
    unpack_u32_array(self:_read_sector(fs), per_sector, fat, (i - 1) * per_sector)
  end
  self.fat = fat
  self.fat_count = n_fat_sectors * per_sector
end

-- Follow a chain in `fat` (0-based, `count` entries) from `start`, returning
-- runs of contiguous sector numbers: { {first, count, pos}, ... } where pos
-- is the byte position of the run's first sector within the stream.
-- `needed` limits the walk to the sectors the stream's size requires
-- ([MS-CFB] 2.7: a chain may be longer than its stream, never shorter).
local function build_runs(fat, count, start, needed, unit)
  local runs = {}
  local s = start
  local n = 0
  while n < needed do
    if s == ENDOFCHAIN then
      fail("sector chain ends after %d of %d sectors", n, needed)
    end
    if s > MAXREGSECT or s >= count then
      fail("sector chain points outside the table (0x%08X)", s)
    end
    local last = runs[#runs]
    if last and last[1] + last[2] == s then
      last[2] = last[2] + 1
    else
      runs[#runs + 1] = { s, 1, n * unit }
    end
    n = n + 1
    s = fat[s]
  end
  return runs
end

function Doc:_chain_runs(start, byte_size)
  local needed = (byte_size + self.sector_size - 1) // self.sector_size
  if needed > self.fat_count then fail("stream larger than the file's FAT allows") end
  return build_runs(self.fat, self.fat_count, start, needed, self.sector_size)
end

-- Read `length` bytes at `offset` within a regular (FAT-chained) stream
-- described by `runs`.
function Doc:_read_runs(runs, offset, length)
  local parts = {}
  local ss = self.sector_size
  -- Binary search for the run containing `offset`.
  local lo, hi = 1, #runs
  while lo < hi do
    local mid = (lo + hi + 1) // 2
    if runs[mid][3] <= offset then lo = mid else hi = mid - 1 end
  end
  local r = lo
  local remaining = length
  while remaining > 0 do
    local run = runs[r]
    if run == nil then fail("read past the end of a sector chain") end
    local within = offset - run[3]
    local avail = run[2] * ss - within
    local take = remaining < avail and remaining or avail
    parts[#parts + 1] = self:_read_at(self:_sector_offset(run[1]) + within, take)
    offset = offset + take
    remaining = remaining - take
    r = r + 1
  end
  return table.concat(parts)
end

-- [MS-CFB] 2.6: the directory is a regular FAT chain of 128-byte entries,
-- stream ID 0 first.
function Doc:_load_directory()
  -- The directory's length is not stored for version 3, so walk its chain.
  local runs = {}
  local s = self.first_dir_sector
  local n = 0
  while s ~= ENDOFCHAIN do
    if s > MAXREGSECT or s >= self.fat_count then
      fail("directory chain points outside the FAT (0x%08X)", s)
    end
    n = n + 1
    if n > self.fat_count then fail("directory chain has a cycle") end
    local last = runs[#runs]
    if last and last[1] + last[2] == s then
      last[2] = last[2] + 1
    else
      runs[#runs + 1] = { s, 1, (n - 1) * self.sector_size }
    end
    s = self.fat[s]
  end
  local data = self:_read_runs(runs, 0, n * self.sector_size)

  local entries = {}
  local count = #data // DIR_ENTRY_SIZE
  for id = 0, count - 1 do
    local p = id * DIR_ENTRY_SIZE + 1
    -- [MS-CFB] 2.6.1 directory entry layout.
    local name_len, obj_type, color, left, right, child =
      string.unpack("<I2BBI4I4I4", data, p + 64)
    local clsid = data:sub(p + 80, p + 95)
    local state_bits = string.unpack("<I4", data, p + 96)
    local start, size_lo, size_hi = string.unpack("<I4I4I4", data, p + 116)
    -- [MS-CFB] 2.6.1 Stream Size: ignore the high 32 bits in version 3 files,
    -- which older writers left uninitialized.
    local size = size_lo
    if self.major_version == 4 then size = size_lo | (size_hi << 32) end

    local name = ""
    if name_len >= 2 and name_len <= 64 and name_len % 2 == 0 then
      name = utf16le_to_utf8(data:sub(p, p + name_len - 3))
    end
    entries[id] = {
      id = id,
      name = name,
      type = OBJECT_TYPES[obj_type] or "invalid",
      color = color,
      left = left,
      right = right,
      child = child,
      clsid = clsid,
      state_bits = state_bits,
      start = start,
      size = size,
    }
  end
  if entries[0] == nil or entries[0].type ~= "root" then
    fail("directory entry 0 is not the root storage")
  end
  self.entries = entries
  self.entry_count = count
end

-- [MS-CFB] 2.4: the mini FAT is a regular chain of sectors holding next-mini-
-- sector numbers; [MS-CFB] 2.6.2: the root entry's start and size describe the
-- mini stream, which is itself a regular chain. Loaded on first use.
function Doc:_load_mini()
  if self.minifat then return end
  local minifat = {}
  local per_sector = self.sector_size // 4
  local s = self.first_minifat_sector
  local n = 0
  while s ~= ENDOFCHAIN and n < self.n_minifat_sectors do
    if s > MAXREGSECT or s >= self.fat_count then
      fail("mini FAT chain points outside the FAT (0x%08X)", s)
    end
    unpack_u32_array(self:_read_sector(s), per_sector, minifat, n * per_sector)
    n = n + 1
    s = self.fat[s]
  end
  self.minifat = minifat
  self.minifat_count = n * per_sector

  local root = self.entries[0]
  if root.start == ENDOFCHAIN or root.size == 0 then
    self.ministream = ""
  else
    local runs = self:_chain_runs(root.start, root.size)
    self.ministream = self:_read_runs(runs, 0, root.size)
  end
end

function Doc:_is_mini(entry)
  return entry.type == "stream" and entry.size < self.mini_cutoff
end

-- Read a whole mini stream ([MS-CFB] 2.4: mini sector N is at byte N x 64 of
-- the mini stream). Mini streams are under the cutoff, so always small.
function Doc:_read_mini(entry)
  self:_load_mini()
  local unit = self.mini_sector_size
  local needed = (entry.size + unit - 1) // unit
  local runs = build_runs(self.minifat, self.minifat_count, entry.start, needed, unit)
  local parts = {}
  for _, run in ipairs(runs) do
    local from = run[1] * unit + 1
    local to = from + run[2] * unit - 1
    if to > #self.ministream then fail("mini sector outside the mini stream") end
    parts[#parts + 1] = self.ministream:sub(from, to)
  end
  return table.concat(parts):sub(1, entry.size)
end

function Doc:_runs_for(entry)
  local runs = self.run_cache[entry.id]
  if not runs then
    runs = self:_chain_runs(entry.start, entry.size)
    self.run_cache[entry.id] = runs
  end
  return runs
end

