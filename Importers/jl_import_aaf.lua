-- Rationals: { n, d } with d > 0, reduced.

local function gcd(a, b)
  a, b = math.abs(a), math.abs(b)
  while b ~= 0 do a, b = b, a % b end
  return a
end

local function R(n, d)
  d = d or 1
  if d == 0 then error("edit: zero denominator", 2) end
  if d < 0 then n, d = -n, -d end
  local g = gcd(n, d)
  if g > 1 then n, d = n // g, d // g end
  return { n = n, d = d }
end
edit.R = R

local function radd(a, b) return R(a.n * b.d + b.n * a.d, a.d * b.d) end
local function rsub(a, b) return R(a.n * b.d - b.n * a.d, a.d * b.d) end
local function rmul(a, b)
  -- cross-reduce first to keep the products small
  local g1, g2 = gcd(a.n, b.d), gcd(b.n, a.d)
  if g1 == 0 then g1 = 1 end
  if g2 == 0 then g2 = 1 end
  return R((a.n // g1) * (b.n // g2), (a.d // g2) * (b.d // g1))
end
local function rdiv(a, b) return rmul(a, R(b.d, b.n)) end
local function rlt(a, b) return a.n * b.d < b.n * a.d end
local function rle(a, b) return a.n * b.d <= b.n * a.d end
local function rnum(a) return a.n / a.d end
edit.radd, edit.rsub, edit.rmul, edit.rdiv, edit.rnum = radd, rsub, rmul, rdiv, rnum

-- An AAF Rational record (MS-01 Rational: Numerator, Denominator) as R.
local function rate_of(r)
  if type(r) ~= "table" or not r.Numerator or not r.Denominator or r.Denominator == 0 or r.Numerator == 0 then
    return nil
  end
  return R(r.Numerator, r.Denominator)
end

-- Seconds of `units` edit units at `rate` (edit units per second).
local function seconds(units, rate)
  if type(units) == "number" then units = R(units) end
  return rnum(rdiv(units, rate))
end

local function is_object(v) return type(v) == "table" and getmetatable(v) == aaf.Object end

-- Data kinds by DataDefinition name. Writers differ: Premiere writes
-- "DataDef_Sound", Pro Tools "Sound" (observed); MS-01 calls the kind Sound.
local function data_kind(c)
  local dd = c:get("DataDefinition")
  local name = is_object(dd) and dd:get("Name") or nil
  if not name then return "unknown" end
  local k = name:gsub("^DataDef_", ""):lower()
  if k == "sound" or k == "legacysound" then return "sound" end
  if k == "picture" or k == "legacypicture" then return "picture" end
  if k == "timecode" or k == "legacytimecode" then return "timecode" end
  return k
end
edit.data_kind = data_kind

