local Import = {}
Import.__index = Import

-- A problem: `where` is text for the report, `pos` its project time (for a
-- marker), `it` the planned item it concerns (to colour and annotate), and
-- `track` the track's display name (for the marker).
function Import:problem(where, message, pos, it, track)
  self.problems[#self.problems + 1] = { where = where, message = message, pos = pos, it = it, track = track }
end

-- A track's display name: its AAF name, or "Track n" when that is blank.
local function track_label(t, ti)
  if t.name and t.name ~= "" then return t.name end
  return "Track " .. tostring(t.track_number or ti)
end

-- Stop with a message (a dialog in REAPER); nothing has been changed.
local function stop(message)
  return { ok = false, message = message }
end

-- An embedded source becomes one extraction task, once per MobID (brief
-- 4.1). Tasks run in extract_step; the item gets its file at finish.
function Import:embedded_task(src, master_name)
  local key = src.mobid
  local task = self.tasks_by_key[key]
  if task then return task end
  task = { src = src, master_name = master_name }
  local st = src.media.essence:get("Data")
  if st and st.stream then
    task.stream = st.stream
    self.total_bytes = self.total_bytes + st.stream.size
  else
    task.err = "embedded essence has no data stream"
  end
  self.tasks_by_key[key] = task
  self.tasks[#self.tasks + 1] = task
  return task
end

-- Start a task's writer, to a temporary file in the media folder.
function Import:start_task(task)
  local src = task.src
  local desc = src.descriptor
  local pcm = nil
  if desc:is_a("PCMDescriptor") then
    local r = desc:get("AudioSamplingRate") or desc:get("SampleRate")
    pcm = {
      channels = desc:get("Channels"), bits = desc:get("QuantizationBits"),
      rate = r and r.Numerator / r.Denominator, block_align = desc:get("BlockAlign"),
      frames = desc:get("Length"), compression = desc:get("Compression"),
    }
  end
  local doc, stream = self.file.doc, task.stream
  local function read(o, n) return doc:read(stream, o, n) end
  self.tmp_count = self.tmp_count + 1
  task.tmp = join(self.media_dir, string.format(".jl_import_aaf_%d.tmp", self.tmp_count))
  local w, err = essence.writer(read, stream.size, pcm, task.tmp)
  if not w then
    os.remove(task.tmp)
    task.err = err
    return
  end
  task.writer = w
end

-- A finished task's file: named from the source or master mob, flat in the
-- media folder (section 6), reusing an identical existing file and
-- otherwise taking the first free " (n)" name.
function Import:finish_task(task)
  local tmp = task.tmp
  if task.writer.fmt.short then
    self:problem(nil, string.format("embedded media for '%s' is shorter than its header says", task.master_name or "?"))
  end
  task.writer = nil
  local base = builder.sanitize(task.src.mob:get("Name") or task.master_name)
  for n = 1, 9999 do
    local leaf = n == 1 and (base .. ".wav") or string.format("%s (%d).wav", base, n)
    local candidate = join(self.media_dir, leaf)
    if not exists(candidate) then
      local ok, rerr = os.rename(tmp, candidate)
      if not ok then
        os.remove(tmp)
        task.err = "could not write " .. candidate .. ": " .. tostring(rerr)
        return
      end
      task.path = candidate
      self.count.extracted = self.count.extracted + 1
      return
    end
    -- Same name and size is not proof of the same audio (brief 4.1).
    if file_size(candidate) == file_size(tmp) and same_content(candidate, tmp) then
      os.remove(tmp)
      task.path = candidate
      self.count.reused = self.count.reused + 1
      return
    end
  end
  os.remove(tmp)
  task.err = "no free file name for " .. base
end

-- The file for a linked source (brief 4.5): the path as given, relative
-- paths against the AAF's folder, then the same file name beside the AAF,
-- matched without regard to case. Returns the path and whether it exists.
function Import:linked_file(src)
  local key = src.mobid
  local planned = self.files[key]
  if planned ~= nil then return planned.path, planned.found end
  local tried = {}
  for _, url in ipairs(src.media.urls) do
    local path, relative = edit.url_to_path(url)
    if path then
      if relative then path = join(self.aaf_dir, path) end
      tried[#tried + 1] = path
    end
  end
  local found = nil
  for _, p in ipairs(tried) do
    if exists(p) then found = p break end
  end
  if not found then
    for _, p in ipairs(tried) do
      local leaf = basename(p:gsub("\\", "/"))
      local beside = join(self.aaf_dir, leaf)
      if exists(beside) then found = beside break end
      local want = leaf:lower()
      for _, name in ipairs(self:aaf_dir_listing()) do
        if name:lower() == want then found = join(self.aaf_dir, name) break end
      end
      if found then break end
    end
  end
  local entry
  if found then
    entry = { path = found, found = true }
    self.count.linked = self.count.linked + 1
  else
    -- Kept as an offline item at the original path, for relinking later.
    entry = { path = tried[1], found = false }
    self.count.missing = self.count.missing + 1
  end
  self.files[key] = entry
  return entry.path, entry.found
end

function Import:aaf_dir_listing()
  if self._listing then return self._listing end
  local out = {}
  local i = 0
  while true do
    local name = self.api.EnumerateFiles(self.aaf_dir, i)
    if not name then break end
    out[#out + 1] = name
    i = i + 1
  end
  self._listing = out
  return out
end

