-- MetaDictionary bootstrap (MS-01 section 27)

-- Hand decoding for meta-definition properties, whose types are fixed by
-- MS-01 27.1 to 27.19. Keyed by property name as the file declares it.
local META_DECODE = {
  Identification = "auid", Name = "string", Description = "string",
  ParentClass = "ref", Properties = "set", IsConcrete = "bool",
  Type = "ref", IsOptional = "bool", LocalIdentification = "u16",
  IsUniqueIdentifier = "bool", Size = "u8", IsSigned = "bool",
  ElementType = "ref", RenamedType = "ref", ReferencedType = "ref",
  ElementCount = "u32", ElementNames = "strings", MemberNames = "strings",
  MemberTypes = "refs",
  -- MS-01 27.19 names this TargetList; files name it TargetSet. Both AUIDArray.
  TargetList = "auids", TargetSet = "auids",
  -- ElementValues is Int64Array for an enumeration (27.6) and AUIDArray for
  -- an extendible enumeration (27.7); resolved by class in _decode_meta.
}

function File:_decode_meta(storage, e, bo, name, class_name)
  local kind = META_DECODE[name]
  if name == "ElementValues" then
    kind = (class_name == "TypeDefinitionExtendibleEnumeration") and "auids" or "i64s"
  end
  local v = e.value
  -- A reference may be stored as a weak reference or as a plain AUID.
  if e.sf == SF_WEAK_OBJECT_REFERENCE then return parse_weak(v, bo).key end
  if e.sf == SF_WEAK_OBJECT_REFERENCE_VECTOR or e.sf == SF_WEAK_OBJECT_REFERENCE_SET then
    local refs = self:_weak_index(storage, flat_name(e, bo), bo)
    local keys = {}
    for i, r in ipairs(refs) do keys[i] = r.key end
    return keys
  end
  if kind == "auid" or kind == "ref" then return auid_key(v, bo) end
  if kind == "string" then return utf16_string(v, bo) end
  if kind == "strings" then return utf16_string_array(v, bo) end
  if kind == "bool" then return v:byte(1) ~= 0 end
  if kind == "u8" then return v:byte(1) end
  if kind == "u16" then return (string.unpack(bo .. "I2", v)) end
  if kind == "u32" then return (string.unpack(bo .. "I4", v)) end
  if kind == "auids" then
    local out = {}
    for i = 1, #v - 15, 16 do out[#out + 1] = auid_key(v:sub(i, i + 15), bo) end
    return out
  end
  if kind == "i64s" then
    local out = {}
    for i = 1, #v - 7, 8 do out[#out + 1] = (string.unpack(bo .. "i8", v, i)) end
    return out
  end
  return v
end

-- Read one MetaDefinition object (a class, property or type definition)
-- given the pid -> name map for meta properties.
function File:_read_meta_object(storage, meta_names, class_name)
  local p = self:_read_props(storage)
  local out = {}
  for _, e in ipairs(p.list) do
    local name = meta_names[e.pid]
    if name and name ~= "Properties" then
      out[name] = self:_decode_meta(storage, e, p.bo, name, class_name)
    end
  end
  return out, p
end

-- Children of a strong reference set property, in index order.
function File:_set_children(storage, e, bo)
  local name = flat_name(e, bo)
  local entries = self:_set_index(storage, name, bo)
  local out = {}
  for i, en in ipairs(entries) do
    local child = self.doc:child(storage, element_name(name, en.key))
    if not child then fail("set element '%s' is missing", element_name(name, en.key)) end
    out[i] = { storage = child, id = en.id }
  end
  return out
end

function File:_load_metadictionary()
  local rootp = self:_read_props(self.doc:root())
  local mde = rootp.by_pid[PID_ROOT_METADICTIONARY]
  if not mde or mde.sf ~= SF_STRONG_OBJECT_REFERENCE then fail("root object has no MetaDictionary") end
  local md = self.doc:child(self.doc:root(), flat_name(mde, rootp.bo))
  if not md then fail("MetaDictionary storage is missing") end
  local mdp = self:_read_props(md)

  -- Pass 1: read every ClassDefinition's own identity and property
  -- definitions using only the bootstrap pids.
  local classes, props_by_pid = {}, {}
  local ce = mdp.by_pid[PID_MD_CLASSDEFINITIONS]
  if not ce then fail("MetaDictionary has no ClassDefinitions") end
  for _, c in ipairs(self:_set_children(md, ce, mdp.bo)) do
    local cp = self:_read_props(c.storage)
    local idv, namev = cp.by_pid[PID_META_IDENTIFICATION], cp.by_pid[PID_META_NAME]
    if not (idv and namev) then fail("class definition without Identification or Name") end
    local parent = cp.by_pid[PID_CLASS_PARENTCLASS]
    local cls = {
      id = auid_key(idv.value, cp.bo),
      name = utf16_string(namev.value, cp.bo),
      parent_id = parent and (parent.sf == SF_WEAK_OBJECT_REFERENCE and parse_weak(parent.value, cp.bo).key
                                or auid_key(parent.value, cp.bo)),
      props = {},          -- pid -> property definition
      props_by_name = {},  -- name -> property definition
      storage = c.storage,
    }
    local pe = cp.by_pid[PID_CLASS_PROPERTIES]
    if pe then
      for _, pd in ipairs(self:_set_children(c.storage, pe, cp.bo)) do
        local pp = self:_read_props(pd.storage)
        local lid, pn, pt, pidv =
          pp.by_pid[PID_PROP_LOCALID], pp.by_pid[PID_META_NAME], pp.by_pid[PID_PROP_TYPE],
          pp.by_pid[PID_META_IDENTIFICATION]
        if not (lid and pn and pt) then fail("property definition in class '%s' is incomplete", cls.name) end
        local def = {
          pid = string.unpack(pp.bo .. "I2", lid.value),
          name = utf16_string(pn.value, pp.bo),
          id = pidv and auid_key(pidv.value, pp.bo),
          type_id = pt.sf == SF_WEAK_OBJECT_REFERENCE and parse_weak(pt.value, pp.bo).key
                    or auid_key(pt.value, pp.bo),
          class = cls,
        }
        cls.props[def.pid] = def
        cls.props_by_name[def.name] = def
        -- MS-02 1.2.1.3.4: property ids are locally unique within a file.
        props_by_pid[def.pid] = def
      end
    end
    classes[cls.id] = cls
  end

  local classes_by_name = {}
  for _, cls in pairs(classes) do classes_by_name[cls.name] = cls end
  for _, cls in pairs(classes) do cls.parent = classes[cls.parent_id] end

  self.classes = classes
  self.classes_by_name = classes_by_name
  self.props_by_pid = props_by_pid
  self:_verify_bootstrap()

  -- Pass 2: type definitions, decoded by meta property name.
  local meta_names = {}
  for pid, def in pairs(props_by_pid) do
    if def.class.name:match("^TypeDefinition") or def.class.name == "MetaDefinition" then
      meta_names[pid] = def.name
    end
  end
  local types, types_by_name = {}, {}
  local te = mdp.by_pid[PID_MD_TYPEDEFINITIONS]
  if te then
    for _, t in ipairs(self:_set_children(md, te, mdp.bo)) do
      local cls = classes[t.storage.clsid]
      local cname = cls and cls.name or "?"
      local td = self:_read_meta_object(t.storage, meta_names, cname)
      td.kind = cname:gsub("^TypeDefinition", "")
      td.class_name = cname
      if not td.Identification then fail("type definition without Identification") end
      types[td.Identification] = td
      if td.Name then types_by_name[td.Name] = td end
    end
  end
  self.types = types
  self.types_by_name = types_by_name
end

-- The bootstrap pids must agree with what the file declares about its own
-- meta-model. A file that disagrees is rejected rather than misread.
function File:_verify_bootstrap()
  local checks = {
    { "MetaDictionary", "ClassDefinitions", PID_MD_CLASSDEFINITIONS },
    { "MetaDictionary", "TypeDefinitions", PID_MD_TYPEDEFINITIONS },
    { "MetaDefinition", "Identification", PID_META_IDENTIFICATION },
    { "MetaDefinition", "Name", PID_META_NAME },
    { "ClassDefinition", "ParentClass", PID_CLASS_PARENTCLASS },
    { "ClassDefinition", "Properties", PID_CLASS_PROPERTIES },
    { "PropertyDefinition", "Type", PID_PROP_TYPE },
    { "PropertyDefinition", "LocalIdentification", PID_PROP_LOCALID },
  }
  for _, c in ipairs(checks) do
    local cls = self.classes_by_name[c[1]]
    local def = cls and cls.props_by_name[c[2]]
    if def and def.pid ~= c[3] then
      fail("file declares %s.%s as pid 0x%04x, expected 0x%04x", c[1], c[2], def.pid, c[3])
    end
    if not def then
      self.bootstrap_unverified = self.bootstrap_unverified or {}
      table.insert(self.bootstrap_unverified, c[1] .. "." .. c[2])
    end
  end
end

