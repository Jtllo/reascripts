local builder = require("builder")

local TITLE = "Import AAF"

-- A menu of compositions at the mouse (native gfx, no toolkit).
local function choose(list)
  local labels = {}
  for i, c in ipairs(list) do
    local name = (c.name or ("Composition " .. i)):gsub("|", "/"):gsub("^[!#<>]+", "")
    labels[i] = string.format("%s  (%s)", name, builder.hms(c.length))
  end
  local x, y = reaper.GetMousePosition()
  gfx.init("", 0, 0, 0, x, y)
  gfx.x, gfx.y = 0, 0
  local pick = gfx.showmenu(table.concat(labels, "|"))
  gfx.quit()
  if pick and pick > 0 then return pick end
  return nil
end

-- Ask about problem markers when there are problems with a position.
local function want_markers(job)
  local n = builder.positioned_problems(job)
  if n == 0 or CONFIG.problem_markers == "never" then return false end
  if CONFIG.problem_markers == "always" then return true end
  local answer = reaper.ShowMessageBox(string.format(
    "The import found %d problem%s at specific points on the timeline.\n\n" ..
    "Mark them? Problem clips are coloured red with a note saying what's wrong, and a marker " ..
    "naming the track and clip is added at each problem. (The details go to the console either way.)",
    n, n == 1 and "" or "s"), TITLE, 4)
  return answer == 6
end

local function complete(job)
  local markers = want_markers(job)
  local result = builder.finish(job, { markers = markers })
  if not result.ok then
    reaper.ShowMessageBox(result.message, TITLE, 0)
    return
  end
  if result.needs_attention or CONFIG.always_report then
    reaper.ShowConsoleMsg(result.report)
  end
end

-- Progress window: a bar and a count, drawn each cycle.
local function draw(job)
  local w, h = gfx.w, gfx.h
  gfx.set(0.15, 0.15, 0.15)
  gfx.rect(0, 0, w, h, 1)
  local frac = job.total_bytes > 0 and job.done_bytes / job.total_bytes or 1
  gfx.set(0.3, 0.3, 0.3)
  gfx.rect(16, h - 34, w - 32, 16, 1)
  gfx.set(0.35, 0.65, 0.95)
  gfx.rect(16, h - 34, math.floor((w - 32) * frac), 16, 1)
  gfx.set(0.9, 0.9, 0.9)
  gfx.x, gfx.y = 16, 14
  gfx.drawstr(string.format("Extracting audio: file %d of %d (%d%%)",
    math.min(job.task_index, #job.tasks), #job.tasks, math.floor(frac * 100)))
  gfx.update()
end

local function main()
  local ok, path = reaper.GetUserFileNameForRead("", TITLE, "aaf")
  if not ok or not path or path == "" then return end
  local job = builder.prepare(reaper, { path = path, choose = choose })
  if not job.ok then
    if not job.cancelled then reaper.ShowMessageBox(job.message, TITLE, 0) end
    return
  end
  if #job.tasks == 0 then
    complete(job)
    return
  end
  local x, y = reaper.GetMousePosition()
  gfx.init(TITLE, 420, 80, 0, x - 210, y - 40)
  local function step()
    -- Closing the window cancels; the project is untouched.
    if gfx.getchar() < 0 then
      builder.cancel(job)
      reaper.ShowConsoleMsg("AAF import cancelled; nothing was added to the project.\n")
      return
    end
    local ok2, done = pcall(builder.extract_step, job, CONFIG.extract_slice, reaper.time_precise)
    if not ok2 then
      gfx.quit()
      builder.cancel(job)
      reaper.ShowMessageBox("The import failed:\n" .. tostring(done), TITLE, 0)
      return
    end
    draw(job)
    if done then
      gfx.quit()
      complete(job)
    else
      reaper.defer(step)
    end
  end
  reaper.defer(step)
end

main()
