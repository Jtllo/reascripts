-- @description Import AAF
-- @author Jon Lloyd
-- @version 1.0
-- @license MIT
-- @about
--   # jl_import_aaf
--
--   Imports an AAF file into the current project: tracks, clips at the AAF's
--   own timecode, embedded or linked audio, fades and crossfades, clip and
--   track gain, pan, and volume and pan automation.
--
--   Pure Lua; nothing else to install. Tested on Windows with REAPER 7.73,
--   with AAFs from Pro Tools 25.12 and Premiere Pro 26.2.2.
-- @changelog
--   1.0: first release.

-- jl_import_aaf: import an AAF file into the current REAPER project.
--
-- What it does
--   Asks for an AAF file, and builds its audio into the project: one mono
--   track per AAF audio track, added after the existing tracks, with items
--   at the AAF's own timecode. Embedded audio is extracted as WAV files into
--   the project's media folder; linked audio is used where it is.
--
-- Why it works the way it does
--   * Pure Lua, no Python, no extensions: nothing to install but this file.
--   * Clips land at the AAF's timecode, measured from the project's start
--     time (File > Project settings), so a session that starts at
--     01:00:00:00 lines up with picture. If the project is empty and its
--     start time doesn't match the AAF's, the import stops and says what to
--     set: no native call lets a script change it.
--   * Everything is extracted and located before the project is touched,
--     then built in one undo step. Extraction runs in the background with a
--     progress window, so REAPER doesn't freeze; closing the window cancels
--     and leaves the project as it was.
--   * Media is identified by its MobID, never its name: Premiere reuses
--     names for different media. A file already in the media folder with
--     the same name is reused only if its content is identical; otherwise
--     the new one gets " (2)".
--   * Linked media is looked for where the AAF says, then beside the AAF.
--     Media that can't be found becomes offline items, ready to relink.
--   * Stereo tracks arrive as separate mono tracks, as the AAF stores them.
--   * Clip gain goes to the item's volume, where it can be seen and stays
--     with the clip if it is moved; clip gain that changes within a clip
--     becomes a take volume envelope. Gain on a whole track goes to the
--     track's fader, or its volume envelope when it changes. Pan follows
--     the same split. Fades and crossfades become linear item fades, as Pro
--     Tools' import shows them.
--   * Silent when all goes well. When anything needs attention, a report
--     with counts and every problem's position goes to the console, and you
--     are offered to mark the problems: problem clips coloured red with a
--     note saying what's wrong, and a marker naming the track and clip.
--
-- Written from the published specifications (Microsoft MS-CFB; AMWA MS-01,
-- MS-02, MS-03, AS-01). Windows; tested with Pro Tools and Premiere Pro AAFs.

