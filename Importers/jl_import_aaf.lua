-- Envelopes

-- AS-01 12.18.2: pan 0 is full left, 1/2 centre, 1 full right; REAPER's
-- D_PAN runs -1 (left) to 1 (right).
local function reaper_pan(v) return v * 2 - 1 end

-- Envelope points for gain or pan curves over a window [w0, w1] (seconds on
-- the envelope's own timeline). Each entry of `curves` is { c = curve,
-- s0 = its span's start, len = its span's length } in the same seconds;
-- curve times are fractions of the span (MS-01 6.18). With several curves
-- (gains that multiply, AS-01 12.17.4) the product is sampled at every
-- point of each. `map` turns a curve value into an envelope value.
local function envelope_points(curves, w0, w1, map, combine)
  local out = {}
  if #curves == 1 then
    local e = curves[1]
    local function at(t) return map(effects.value_at(e.c, (t - e.s0) / e.len)) end
    out[#out + 1] = { t = w0, v = at(w0) }
    for _, pt in ipairs(e.c.points) do
      local t = e.s0 + pt.t * e.len
      if t > w0 and t < w1 then out[#out + 1] = { t = t, v = map(pt.v) } end
    end
    out[#out + 1] = { t = w1, v = at(w1) }
    return out
  end
  local times = { w0, w1 }
  for _, e in ipairs(curves) do
    for _, pt in ipairs(e.c.points) do
      local t = e.s0 + pt.t * e.len
      if t > w0 and t < w1 then times[#times + 1] = t end
    end
  end
  table.sort(times)
  local last
  for _, t in ipairs(times) do
    if t ~= last then
      local v
      for _, e in ipairs(curves) do
        local x = map(effects.value_at(e.c, (t - e.s0) / e.len))
        v = v and combine(v, x) or x
      end
      out[#out + 1] = { t = t, v = v }
      last = t
    end
  end
  return out
end

-- An envelope block as REAPER stores it in an item or track state chunk
-- (observed with tools/reaper_env_probe.lua in REAPER 7.73): active and
-- visible, linear points (shape 0). Volume envelopes hold plain amplitude
-- (1 = 0 dB) and say VOLTYPE 1 (fader scaling).
local function envelope_block(tag, points, volume)
  local lines = { "<" .. tag, "ACT 1 -1", "VIS 1 1 1", "LANEHEIGHT 0 0", "ARM 0", "DEFSHAPE 0 -1 -1" }
  if volume then lines[#lines + 1] = "VOLTYPE 1" end
  for _, pt in ipairs(points) do
    lines[#lines + 1] = string.format("PT %.12g %.12g 0", pt.t, pt.v)
  end
  lines[#lines + 1] = ">"
  return table.concat(lines, "\n") .. "\n"
end

-- Insert envelope blocks before a state chunk's closing ">".
local function add_to_chunk(chunk, blocks)
  local head = chunk:match("^(.*)>%s*$")
  if not head then return nil end
  if not head:match("\n$") then head = head .. "\n" end
  return head .. table.concat(blocks) .. ">\n"
end

-- Pan envelope values run in D_PAN's direction (-1 left). REAPER's API
-- documentation doesn't say; verified in REAPER 7.73 with the "auto" track
-- of tests/fixtures/effects.aaf.
local function pan_env_value(v) return reaper_pan(v) end

