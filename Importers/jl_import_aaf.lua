-- Raw property streams (MS-02 1.2.1.3)

local File = {}
File.__index = File
local Object = {}
Object.__index = Object

-- Parse an object's "properties" stream into
-- { bo = "<"|">", version = n, list = {entry...}, by_pid = {pid = entry} }
-- where entry = { pid, sf, value } and value is the flat bytes.
function File:_read_props(storage)
  local cached = self._props_cache[storage.id]
  if cached then return cached end
  local st = self.doc:child(storage, PROPERTIES)
  if not st then fail("object storage '%s' has no properties stream", storage.name) end
  local s = self.doc:read_all(st)
  if #s < 4 then fail("properties stream of '%s' is too short", storage.name) end
  -- MS-02 1.2.1.3.3 PropertyIndexHeader: _byteOrder (1), _formatVersion (1),
  -- _entryCount (2).
  local bo = BYTE_ORDERS[s:byte(1)]
  if not bo then fail("unknown byte order 0x%02x in '%s'", s:byte(1), storage.name) end
  local version = s:byte(2)
  local count = string.unpack(bo .. "I2", s, 3)
  local list, by_pid = {}, {}
  -- MS-02 1.2.1.3.4 PropertyIndexEntry: _pid (2), _storedForm (2), _length (2),
  -- followed by the flat values in the same order (MS-02 1.5.1: contiguous).
  local pos = 5
  local vpos = 5 + 6 * count
  for _ = 1, count do
    local pid, sf, len = string.unpack(bo .. "I2I2I2", s, pos)
    pos = pos + 6
    if vpos + len - 1 > #s then fail("property 0x%04x of '%s' runs past the stream", pid, storage.name) end
    local e = { pid = pid, sf = sf, value = s:sub(vpos, vpos + len - 1) }
    vpos = vpos + len
    list[#list + 1] = e
    by_pid[pid] = e
  end
  local p = { bo = bo, version = version, list = list, by_pid = by_pid }
  self._props_cache[storage.id] = p
  return p
end

-- MS-02 1.2.1.4 to 1.2.1.6: a strong reference's flat value is the name of
-- the child storage (or of the collection); MS-02 1.2.1.10 and 1.4.3: a data
-- stream's flat value is a byte order followed by the stream name.
local function flat_name(e, bo)
  if e.sf == SF_DATA_STREAM then
    return utf16_string(e.value:sub(2), bo)
  end
  return utf16_string(e.value, bo)
end

-- Element storages of vectors and sets are named <collection>{<local key>}.
-- MS-02 1.3 ("Storage and Stream Naming") is marked TBS; the lower-case hex
-- local key is observed.
local function element_name(collection, key)
  return string.format("%s{%x}", collection, key)
end

-- MS-02 1.2.1.5: strong reference vector index "<name> index".
function File:_vector_index(parent, name, bo)
  local st = self.doc:child(parent, name .. " index")
  if not st then fail("missing vector index '%s index'", name) end
  local s = self.doc:read_all(st)
  -- MS-02 1.2.1.5.3 StrongReferenceVectorIndexHeader: _entryCount,
  -- _firstFreeKey, _lastFreeKey (4 bytes each); 1.2.1.5.4 entries: _localKey.
  local count = string.unpack(bo .. "I4", s, 1)
  local keys = {}
  local pos = 13
  for i = 1, count do
    keys[i] = string.unpack(bo .. "I4", s, pos)
    pos = pos + 4
  end
  return keys
end

-- MS-02 1.2.1.6: strong reference set index "<name> index". Returns a list
-- of { key = local key, id = identification bytes } in index order, and the
-- identification pid.
function File:_set_index(parent, name, bo)
  local st = self.doc:child(parent, name .. " index")
  if not st then fail("missing set index '%s index'", name) end
  local s = self.doc:read_all(st)
  -- MS-02 1.2.1.6.3 StrongReferenceSetIndexHeader: _entryCount,
  -- _firstFreeKey, _lastFreeKey (4 each), _identificationPid (2),
  -- _identificationSize (1).
  local count, _, _, id_pid, id_size = string.unpack(bo .. "I4I4I4I2B", s, 1)
  local entries = {}
  local pos = 16
  for i = 1, count do
    -- MS-02 1.2.1.6.4 StrongReferenceSetIndexEntry: _localKey (4),
    -- _referenceCount (4), _identification (_identificationSize).
    local key = string.unpack(bo .. "I4", s, pos)
    local ident = s:sub(pos + 8, pos + 8 + id_size - 1)
    entries[i] = { key = key, id = ident }
    pos = pos + 8 + id_size
  end
  return entries, id_pid
end

-- MS-02 1.2.1.7.3 WeakObjectReference: _referencedPropertyIndex (2),
-- _identificationPid (2), _identificationSize (1), _identification.
local function parse_weak(value, bo)
  local tag, id_pid, id_size = string.unpack(bo .. "I2I2B", value)
  return { tag = tag, key_pid = id_pid, key = auid_key(value:sub(6, 5 + id_size), bo) }
end

-- MS-02 1.2.1.8 and 1.2.1.9: weak reference vector and set indexes share a
-- layout. Header: _entryCount (4), _referencedPropertyIndex (2),
-- _identificationPid (2), _identificationSize (1); then the keys.
function File:_weak_index(parent, name, bo)
  local st = self.doc:child(parent, name .. " index")
  if not st then fail("missing weak reference index '%s index'", name) end
  local s = self.doc:read_all(st)
  local count, tag, id_pid, id_size = string.unpack(bo .. "I4I2I2B", s, 1)
  local refs = {}
  local pos = 10
  for i = 1, count do
    refs[i] = { tag = tag, key_pid = id_pid, key = auid_key(s:sub(pos, pos + id_size - 1), bo) }
    pos = pos + id_size
  end
  return refs
end

