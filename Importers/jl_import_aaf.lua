-- Compositions

local Context = {}
Context.__index = Context

local function new_context(file)
  local ctx = setmetatable({ file = file, mobs = {}, essence = {} }, Context)
  local content = file:header():get("Content")
  for _, m in ipairs(content:get("Mobs") or {}) do ctx.mobs[m:get("MobID")] = m end
  for _, e in ipairs(content:get("EssenceData") or {}) do ctx.essence[e:get("MobID")] = e end
  -- Parameter definitions by ID (MS-01 8.5), for their names.
  ctx.param_names = {}
  local dict = file:header():get("Dictionary")
  for _, pd in ipairs(is_object(dict) and dict:get("ParameterDefinitions") or {}) do
    local id = pd:get("Identification")
    if id then ctx.param_names[id] = pd:get("Name") end
  end
  return ctx
end

-- Every CompositionMob, flagged top_level if its UsageCode says so or no
-- other composition refers to it (brief 4.9).
function edit.compositions(file)
  local ctx = new_context(file)
  local referenced = {}
  local seen = {}
  local function scan(o)
    if seen[o] then return end
    seen[o] = true
    if o:is_a("SourceReference") then
      local sid = o:get("SourceID")
      if sid then referenced[sid] = true end
    end
    for _, p in ipairs(o:properties()) do
      local sf = p.sf
      if sf == aaf.SF.STRONG or sf == aaf.SF.STRONG_VECTOR or sf == aaf.SF.STRONG_SET then
        local v = o:value_of(p)
        if is_object(v) then scan(v) else for _, c in ipairs(v) do scan(c) end end
      end
    end
  end
  local comps = {}
  for id, m in pairs(ctx.mobs) do
    if m:is_a("CompositionMob") then
      comps[#comps + 1] = m
      scan(m)
    end
  end
  local out = {}
  for _, m in ipairs(comps) do
    local id = m:get("MobID")
    local usage = m:get("UsageCode")
    -- Length of the longest audio track. Timecode tracks are left out: Pro
    -- Tools writes them 24 hours long (observed).
    local length = 0
    for _, s in ipairs(m:get("Slots") or {}) do
      local seg, rate = s:get("Segment"), rate_of(s:get("EditRate"))
      local len = is_object(seg) and data_kind(seg) == "sound" and seg:get("Length")
      if rate and len then length = math.max(length, seconds(len, rate)) end
    end
    out[#out + 1] = {
      mob = m, mobid = id, name = m:get("Name"), usage = usage, length = length,
      top_level = usage == "Usage_TopLevel" or not referenced[id],
    }
  end
  table.sort(out, function(a, b)
    if a.top_level ~= b.top_level then return a.top_level end
    return (a.name or "") < (b.name or "") or ((a.name or "") == (b.name or "") and a.mobid < b.mobid)
  end)
  return out
end

