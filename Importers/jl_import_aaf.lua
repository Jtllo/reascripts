-- Effects (milestone 4; brief section 7)

-- Tally an effect that isn't applied, for one summary line per kind.
function Import:unapplied_effect(label, reason)
  local key = label .. ": " .. reason
  self.unapplied[key] = (self.unapplied[key] or 0) + 1
end

function Import:report_unapplied()
  local keys = {}
  for k in pairs(self.unapplied) do keys[#keys + 1] = k end
  table.sort(keys)
  for _, k in ipairs(keys) do
    local n = self.unapplied[k]
    self:problem(nil, string.format("%s (%d time%s)", k, n, n == 1 and "" or "s"))
  end
end


-- Check a dissolve parameter can be a linear fade. Premiere's Levels of 0
-- at both ends mean the AS-01 12.19.1 default; fades are linear (brief
-- section 7). Any other shape is noted as made linear.
function Import:check_fade_curve(par, label)
  local c = effects.curve(par)
  if not par or not c or effects.degenerate(c) then return end
  local pts = c.points
  if c.linear and #pts == 2 and pts[1].t <= 0 and pts[2].t >= 1
     and (math.abs(pts[1].v) < 1e-9 or math.abs(pts[1].v - 1) < 1e-9) then
    return
  end
  self:unapplied_effect(label, "fade curve shape not reproduced; made linear")
end

-- Work out a track's effects and its items' (take volume and pan, and
-- fades). Returns the track's fader volume and pan.
function Import:plan_effects(t, items, to_project)
  local tfx = { vol = 1, pan = nil, gains = {}, pan_curve = nil }
  local function span(e) return to_project(e.pos), rnum(rdiv(edit.R(e.length), t.rate)) end
  -- Track-level (AS-01 12.17.3): constant gain on the fader, varying gain
  -- as the track's volume envelope; pan likewise (brief section 7).
  for _, e in ipairs(t.effects) do
    local kind = effects.kind(e)
    if kind == "gain" then
      local c = effects.curve(effects.param(e, "amplitude"))
      local v = c and effects.flat_value(c, e.length)
      if v then tfx.vol = tfx.vol * v
      elseif c then
        local s0, len = span(e)
        tfx.gains[#tfx.gains + 1] = { c = c, s0 = s0, len = len }
      else self:unapplied_effect("track gain", "value unreadable") end
    elseif kind == "pan" then
      local c = effects.curve(effects.param(e, "pan"))
      local v = c and effects.flat_value(c, e.length)
      -- AS-01 12.18: pans are not nested; the top-level one applies.
      if tfx.pan or tfx.pan_curve then
        -- an inner pan: ignored
      elseif v then tfx.pan = reaper_pan(v)
      elseif c then
        local s0, len = span(e)
        tfx.pan_curve = { c = c, s0 = s0, len = len }
      else self:unapplied_effect("track pan", "value unreadable") end
    else
      self:unapplied_effect(effects.label(e), "track effect not applied")
    end
  end
  for _, g in ipairs(tfx.gains) do
    if not g.c.linear then self:unapplied_effect("track gain", "curve interpolation made linear") end
  end
  if tfx.pan_curve and not tfx.pan_curve.c.linear then self:unapplied_effect("track pan", "curve interpolation made linear") end

  -- Clip-level: constant gain on the item's volume (brief section 7),
  -- varying gain as a take volume envelope; pan on the take. Envelope
  -- times run from the item's start.
  for _, it in ipairs(items) do
    local vol, pan = 1, nil
    local gains, pan_curve = {}, nil
    local item_start = to_project(it.ev.pos) + it.cut
    local function span(e) return to_project(e.pos) - item_start, rnum(rdiv(edit.R(e.length), t.rate)) end
    for _, e in ipairs(it.ev.effects) do
      local kind = effects.kind(e)
      if kind == "gain" then
        local c = effects.curve(effects.param(e, "amplitude"))
        local v = c and effects.flat_value(c, e.length)
        -- AS-01 12.17.4: gains multiply.
        if v then vol = vol * v
        elseif c then
          local s0, len = span(e)
          gains[#gains + 1] = { c = c, s0 = s0, len = len }
          if not c.linear then self:unapplied_effect("clip gain", "curve interpolation made linear") end
        else self:unapplied_effect("clip gain", "value unreadable") end
      elseif kind == "pan" then
        local c = effects.curve(effects.param(e, "pan"))
        local v = c and effects.flat_value(c, e.length)
        if pan or pan_curve then
          -- an inner pan: ignored (AS-01 12.18)
        elseif v then pan = reaper_pan(v)
        elseif c then
          local s0, len = span(e)
          pan_curve = { c = c, s0 = s0, len = len }
          if not c.linear then self:unapplied_effect("clip pan", "curve interpolation made linear") end
        else self:unapplied_effect("clip pan", "value unreadable") end
      else
        self:unapplied_effect(effects.label(e), "clip effect not applied")
      end
    end
    it.vol, it.pan = vol, pan
    if #gains > 0 then
      it.vol_env = envelope_points(gains, 0, it.length, function(x) return x end, function(a, b) return a * b end)
    end
    if pan_curve then
      it.pan_env = envelope_points({ pan_curve }, 0, it.length, pan_env_value)
    end
    -- MS-01 7.7's deprecated fade properties, in the track's edit units.
    local ev = it.ev
    for _, which in ipairs({ "fade_in", "fade_out" }) do
      local fd = ev[which]
      if fd and fd.length and fd.type ~= "FadeNone" then
        it[which] = math.max(it[which] or 0, rnum(rdiv(edit.R(fd.length), t.rate)))
        if fd.type and fd.type ~= "FadeLinearAmp" then
          self:unapplied_effect("clip fade " .. tostring(fd.type), "made linear")
        end
      end
    end
  end

  -- Transitions (MS-01 7.2): a fade-out on the clip before and a fade-in
  -- on the clip after, each the transition's length; with no clip on one
  -- side it is a fade from or to silence.
  for _, xf in ipairs(t.crossfades) do
    local e = xf.effect
    local kind = e and effects.kind(e)
    local label = e and effects.label(e) or "transition"
    if kind == "dissolve" then
      self:check_fade_curve(effects.param(e, "level"), label)
    elseif kind == "dissolve2" then
      self:check_fade_curve(effects.param(e, "outgoing"), label)
      self:check_fade_curve(effects.param(e, "incoming"), label)
    else
      self:unapplied_effect(label, "transition made a linear crossfade")
    end
    local len = rnum(rdiv(edit.R(xf.length), t.rate))
    local a = xf.before and self.item_of[xf.before]
    local b = xf.after and self.item_of[xf.after]
    if a then a.fade_out = math.max(a.fade_out or 0, len) end
    if b then b.fade_in = math.max(b.fade_in or 0, len) end
  end

  -- Fades fit their items; a clip trimmed at project zero loses the part
  -- of its fade-in that was cut.
  for _, it in ipairs(items) do
    if it.fade_in then it.fade_in = math.max(0, math.min(it.fade_in - it.cut, it.length)) end
    if it.fade_out then it.fade_out = math.min(it.fade_out, it.length) end
  end
  return tfx
end

function Import:mob(id)
  if not self._mobs then
    self._mobs = {}
    for _, m in ipairs(self.file:header():get("Content"):get("Mobs") or {}) do self._mobs[m:get("MobID")] = m end
  end
  return self._mobs[id]
end

-- The import report (section 5): counts, then every problem with where it is.
function Import:report_text(tl, comp)
  local c = self.count
  local lines = {
    string.format("AAF import: %s", comp.name or "(unnamed composition)"),
    string.format("  tracks %d, clips %d, files extracted %d (reused %d), media linked %d, media missing %d, skipped %d, markers %d, envelopes %d",
      c.tracks, c.clips, c.extracted, c.reused, c.linked, c.missing, c.skipped, c.markers, c.envelopes),
  }
  if tl.timecode then
    lines[#lines + 1] = string.format("  starts at %s", builder.timecode_text(tl.timecode.start,
      tl.timecode.fps or rnum(tl.timecode.rate), tl.timecode.drop))
  end
  if #self.problems > 0 then
    lines[#lines + 1] = string.format("  %d problem%s:", #self.problems, #self.problems == 1 and "" or "s")
    for _, p in ipairs(self.problems) do
      lines[#lines + 1] = "  - " .. (p.where and (p.where .. ": ") or "") .. p.message
    end
  end
  return table.concat(lines, "\n") .. "\n"
end

