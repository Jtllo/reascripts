-- Classes and types

-- Walk a class up its ParentClass chain (MS-01 27.2).
function File:class_chain(cls)
  local out, seen = {}, {}
  while cls and not seen[cls] do
    out[#out + 1] = cls
    seen[cls] = true
    cls = cls.parent
  end
  return out
end

-- The nearest class in the chain that MS-01 defines.
function File:spec_class(cls)
  for _, c in ipairs(self:class_chain(cls)) do
    if SPEC_CLASSES[c.name] then return c end
  end
  return nil
end

function File:type_name(type_id)
  local t = self.types[type_id]
  return t and t.Name or ("type " .. aaf.auid_string(type_id))
end

-- Size in bytes of a fixed-size type, or nil for a variable-size one.
function File:type_size(t, depth)
  depth = (depth or 0) + 1
  if depth > 32 then fail("type definitions nest too deeply") end
  local k = t.kind
  if k == "Integer" then return t.Size end
  if k == "Character" then return 2 end           -- MS-01 27.5: a 2-byte character
  if k == "Enumeration" then
    local et = self.types[t.ElementType]
    return et and self:type_size(et, depth)
  end
  if k == "ExtendibleEnumeration" then return 16 end  -- MS-01 27.7: AUID values
  if k == "Rename" then
    local rt = self.types[t.RenamedType]
    return rt and self:type_size(rt, depth)
  end
  if k == "Record" then
    local total = 0
    for _, mid in ipairs(t.MemberTypes or {}) do
      local mt = self.types[mid]
      local sz = mt and self:type_size(mt, depth)
      if not sz then return nil end
      total = total + sz
    end
    return total
  end
  if k == "FixedArray" then
    local et = self.types[t.ElementType]
    local sz = et and self:type_size(et, depth)
    return sz and sz * t.ElementCount
  end
  return nil
end

-- Decode a flat SF_DATA value of type `t`. Returns a Lua value:
--   integers -> number; Boolean -> boolean; other enumerations -> the
--   element name (or the number if unnamed); extendible enumerations -> the
--   element name (or the AUID key); AUID -> 16-byte key; MobIDType ->
--   32-byte string; strings -> UTF-8; records -> table by member name;
--   arrays and sets -> Lua arrays; Indirect/Opaque -> { raw = bytes }.
function File:decode(t, v, bo, depth)
  depth = (depth or 0) + 1
  if depth > 32 then fail("type definitions nest too deeply") end
  local k = t.kind
  if k == "Integer" then
    local fmt = bo .. (t.IsSigned and "i" or "I") .. t.Size
    return (string.unpack(fmt, v))
  end
  if k == "Character" then return utf16_string(v, bo) end
  if k == "String" then return utf16_string(v, bo) end
  if k == "Rename" then
    return self:decode(assert(self.types[t.RenamedType], "unknown renamed type"), v, bo, depth)
  end
  if k == "Enumeration" then
    local n = self:decode(assert(self.types[t.ElementType], "unknown enum element type"), v, bo, depth)
    -- MS-01 Boolean is an enumeration of False (0) and True (1).
    if t.Name == "Boolean" then return n ~= 0 end
    for i, val in ipairs(t.ElementValues or {}) do
      if val == n then return t.ElementNames[i] end
    end
    return n
  end
  if k == "ExtendibleEnumeration" then
    local key = auid_key(v, bo)
    for i, val in ipairs(t.ElementValues or {}) do
      if val == key then return t.ElementNames[i] end
    end
    return key
  end
  if k == "Record" then
    if t.Name == "AUID" then return auid_key(v, bo) end
    if t.Name == "MobIDType" then return v end
    local out = {}
    local pos = 1
    for i, mid in ipairs(t.MemberTypes or {}) do
      local mt = self.types[mid]
      if not mt then return { raw = v } end
      local sz = self:type_size(mt)
      if not sz then return { raw = v } end
      out[t.MemberNames[i] or i] = self:decode(mt, v:sub(pos, pos + sz - 1), bo, depth)
      pos = pos + sz
    end
    return out
  end
  if k == "FixedArray" or k == "VariableArray" or k == "Set" then
    local et = self.types[t.ElementType]
    if not et then return { raw = v } end
    if et.kind == "String" or (et.kind == "Character" and k == "VariableArray") then
      return utf16_string_array(v, bo)
    end
    local sz = self:type_size(et)
    if not sz or sz == 0 then return { raw = v } end
    local out = {}
    for pos = 1, #v - sz + 1, sz do
      out[#out + 1] = self:decode(et, v:sub(pos, pos + sz - 1), bo, depth)
    end
    return out
  end
  -- MS-01 27.9 defines an Indirect value as typed per instance but gives no
  -- byte layout. Observed (cross-checked against pyaaf2): a byte order byte
  -- as in MS-02 1.5.1, the value's type AUID (16 bytes), then the value.
  -- Opaque (MS-01 27.11) values are left raw.
  if k == "Indirect" and #v >= 17 then
    local ibo = BYTE_ORDERS[v:byte(1)]
    local it = ibo and self.types[auid_key(v:sub(2, 17), ibo)]
    if it then
      return { indirect = it.Name, value = self:decode(it, v:sub(18), ibo, depth), raw = v }
    end
  end
  return { raw = v }
end

