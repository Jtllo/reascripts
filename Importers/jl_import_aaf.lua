-- Public API

function Doc:root()
  return self.entries[0]
end

function Doc:entry(id)
  return self.entries[id]
end

-- Direct children of a storage (or the root), in tree order.
-- [MS-CFB] 2.6.4: a storage's Child ID points at the top of a binary tree of
-- its children linked by Left and Right Sibling IDs; an in-order walk gives
-- them in the tree's sort order.
function Doc:children(entry)
  local out = {}
  if entry.type ~= "storage" and entry.type ~= "root" then return out end
  local stack = {}
  local visited = {}
  local node = entry.child
  while true do
    while node ~= NOSTREAM do
      if node > MAXREGSID or self.entries[node] == nil then
        fail("sibling tree under '%s' points outside the directory", entry.name)
      end
      if visited[node] then fail("sibling tree under '%s' has a cycle", entry.name) end
      visited[node] = true
      stack[#stack + 1] = node
      node = self.entries[node].left
    end
    if #stack == 0 then break end
    node = table.remove(stack)
    out[#out + 1] = self.entries[node]
    node = self.entries[node].right
  end
  return out
end

-- [MS-CFB] 2.6.1: names compare case-insensitively. This folds ASCII only;
-- AAF's own storage and stream names are ASCII.
function Doc:child(entry, name)
  local want = name:upper()
  for _, c in ipairs(self:children(entry)) do
    if c.name == name or c.name:upper() == want then return c end
  end
  return nil
end

-- Resolve a slash-separated path from the root, e.g. "Header-2/Content-3b03".
function Doc:find(path)
  local e = self:root()
  for part in path:gmatch("[^/]+") do
    e = self:child(e, part)
    if e == nil then return nil end
  end
  return e
end

-- Read `length` bytes of a stream starting at byte `offset` (0-based).
-- Reads are clipped to the stream's end.
function Doc:read(entry, offset, length)
  if entry.type ~= "stream" then fail("'%s' is not a stream", entry.name) end
  offset = offset or 0
  length = length or (entry.size - offset)
  if offset < 0 or offset > entry.size then fail("offset %d outside stream '%s'", offset, entry.name) end
  if offset + length > entry.size then length = entry.size - offset end
  if length <= 0 then return "" end
  if self:_is_mini(entry) then
    return self:_read_mini(entry):sub(offset + 1, offset + length)
  end
  return self:_read_runs(self:_runs_for(entry), offset, length)
end

-- Whole stream as one string. For property streams and other small data;
-- use chunks() for essence.
function Doc:read_all(entry)
  return self:read(entry, 0, entry.size)
end

-- Iterate a stream in pieces of at most `chunk_size` bytes:
--   for offset, data in doc:chunks(entry, 1 << 20) do ... end
function Doc:chunks(entry, chunk_size, start_offset)
  local pos = start_offset or 0
  return function()
    if pos >= entry.size then return nil end
    local at = pos
    local data = self:read(entry, pos, chunk_size)
    pos = pos + #data
    return at, data
  end
end

function Doc:close()
  if self.fh then self.fh:close() end
  self.fh = nil
end

-- Open a compound file. Returns a document, or nil and an error message.
function cfb.open(path)
  local fh, err = io.open(path, "rb")
  if not fh then return nil, err end
  local doc = setmetatable({ fh = fh, path = path, run_cache = {} }, Doc)
  local ok, e = pcall(function()
    doc.file_size = fh:seek("end")
    doc:_load_header_and_fat()
    doc:_load_directory()
  end)
  if not ok then
    fh:close()
    return nil, e
  end
  return doc
end

return cfb

end

