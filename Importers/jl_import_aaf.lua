-- The import, in three stages so that extraction can run across REAPER's
-- defer cycles (section 7, milestone 5): prepare reads and plans; extract
-- writes the embedded media; finish builds the project in one undo block.
-- The project is untouched until finish.

-- Stage 1. `opts`:
--   path          the AAF file
--   choose(list)  picks a composition when there is more than one top-level
--                 one: list of { name, length }, returns an index or nil
-- Returns a job ({ ok = true, ... }) or { ok = false, message }.
function builder.prepare(api, opts)
  local proj, projfn = api.EnumProjects(-1)
  if not projfn or projfn == "" then
    return stop("Save the project first: an unsaved project has no media folder for the extracted audio.")
  end
  local media_dir = api.GetProjectPathEx(proj)
  if not media_dir or media_dir == "" then return stop("Could not find the project's media folder.") end

  local f, err = aaf.open(opts.path)
  if not f then return stop("Could not read the AAF file:\n" .. tostring(err)) end

  local imp = setmetatable({
    api = api, file = f, proj = proj, projfn = projfn, media_dir = media_dir, aaf_dir = dirname(opts.path),
    problems = {}, files = {}, tmp_count = 0, item_of = {}, unapplied = {},
    tasks = {}, tasks_by_key = {}, total_bytes = 0, done_bytes = 0, task_index = 1,
    count = { tracks = 0, clips = 0, extracted = 0, reused = 0, linked = 0, missing = 0,
              skipped = 0, markers = 0, envelopes = 0 },
  }, Import)
  local ok, result = pcall(Import.plan, imp, opts)
  if not ok then
    f:close()
    return stop("The import failed:\n" .. tostring(result))
  end
  if not result.ok then f:close() end
  return result
end

function Import:plan(opts)
  local api, f, proj = self.api, self.file, self.proj

  -- Composition (brief 4.9).
  local comps = edit.compositions(f)
  local tops = {}
  for _, c in ipairs(comps) do if c.top_level then tops[#tops + 1] = c end end
  if #tops == 0 then tops = comps end
  if #tops == 0 then return stop("The AAF file contains no composition.") end
  local comp = tops[1]
  if #tops > 1 then
    local list = {}
    for i, c in ipairs(tops) do list[i] = { name = c.name or ("Composition " .. i), length = c.length } end
    local pick = opts.choose and opts.choose(list)
    if not pick then return { ok = false, cancelled = true, message = "cancelled" } end
    comp = tops[pick]
  end
  local tl = edit.timeline(f, comp.mob)

  -- Timecode against the project (brief 3.3).
  local offset = api.GetProjectTimeOffset(proj, false)
  local fps, drop = api.TimeMap_curFrameRate(proj)
  local tc = tl.timecode
  local tc_start = tc and tc.seconds or 0
  if tc then
    local aaf_fps = rnum(tc.rate)
    local frame = 1 / aaf_fps
    if math.abs(aaf_fps - fps) > 0.001 or (tc.drop and true or false) ~= (drop and true or false) then
      self:problem(nil, string.format("the AAF's timecode runs at %.3f fps%s, the project at %.3f fps%s",
        aaf_fps, tc.drop and " drop-frame" or "", fps, drop and " drop-frame" or ""))
    end
    local empty = api.CountMediaItems(proj) == 0
    if empty and math.abs(offset - tc_start) > frame / 2 then
      -- No native call sets the project start time or frame rate.
      return stop(string.format(
        "This AAF starts at %s (%.3f fps%s).\n\nSet File > Project settings > Project start time to %s " ..
        "and the frame rate to %.3f%s, then import again.\n\nThe project is empty, and a script can't " ..
        "change these settings itself.",
        builder.timecode_text(tc.start, tc.fps or aaf_fps, tc.drop), aaf_fps, tc.drop and " drop-frame" or "",
        builder.timecode_text(tc.start, tc.fps or aaf_fps, tc.drop), aaf_fps, tc.drop and " drop-frame" or ""))
    end
  end

  -- Items and media. Embedded media is queued for extract_step; the project
  -- is not touched (section 5, layer 4).
  local plan = {}
  for ti, t in ipairs(tl.tracks) do
    local items = {}
    for _, ev in ipairs(t.events) do
      local pos = tc_start + ev.start - offset
      local where = string.format("track %d%s at %s", ti, t.name and t.name ~= "" and (" (" .. t.name .. ")") or "",
        hms(tc_start + ev.start))
      local src = ev.source
      local tname = track_label(t, ti)
      if not src then
        -- Reported by the edit layer ("clip source not found").
        self.count.skipped = self.count.skipped + 1
      else
        local master = src.hops[1] and self:mob(src.hops[1].mobid)
        local master_name = master and master:get("Name") or nil
        local path, task, offline
        if src.media.kind == "embedded" then
          task = self:embedded_task(src, master_name)
        elseif src.media.kind == "linked" then
          local found
          path, found = self:linked_file(src)
          if not path then
            self:problem(where, "clip skipped: its media locator is not a file path", pos, nil, tname)
            self.count.skipped = self.count.skipped + 1
          elseif not found then
            offline = path
          end
        else
          self:problem(where, "clip skipped: its media is neither embedded nor linked", pos, nil, tname)
          self.count.skipped = self.count.skipped + 1
        end
        if path or task then
          local it = {
            pos = pos, length = ev.duration, startoffs = rnum(rdiv(src.offset, src.sample_rate)),
            path = path, task = task, name = master_name or src.mob:get("Name") or (path and basename(path)) or "",
            where = where, ev = ev, cut = 0, track = tname,
          }
          if offline then self:problem(where, "media not found, item left offline: " .. offline, pos, it, tname) end
          -- One channel of a multichannel file: only left or right is
          -- expressible (I_CHANMODE 3 and 4).
          local ch = ev.channel
          if ch and (src.channels or 1) > 1 then
            if ch == 1 or ch == 2 then
              it.chanmode = 2 + ch
            else
              self:problem(where, string.format("channel %d of a %d-channel file can't be selected; the whole file plays", ch, src.channels), pos, it, tname)
            end
          end
          -- Before project zero: trimmed at zero, keeping the rest in sync.
          if it.pos < 0 then
            local cut = -it.pos
            if cut >= it.length then
              self:problem(where, string.format("clip ends before project zero; skipped"), pos, nil, tname)
              it = nil
              self.count.skipped = self.count.skipped + 1
            else
              it.pos, it.length, it.startoffs, it.cut = 0, it.length - cut, it.startoffs + cut, cut
              self:problem(where, string.format("clip starts %.3f s before project zero; trimmed", cut), 0, it, tname)
            end
          end
          if it then
            items[#items + 1] = it
            self.item_of[ev] = it
          end
        end
      end
    end
    plan[ti] = items
  end
  local track_fx = {}
  for ti, t in ipairs(tl.tracks) do
    -- Project seconds of a position in this track's edit units.
    local function to_project(units) return tc_start + rnum(rdiv(edit.R(units), t.rate)) - offset end
    track_fx[ti] = self:plan_effects(t, plan[ti], to_project)
  end
  self:report_unapplied()
  for _, r in ipairs(tl.report) do
    local label = (r.track and r.track ~= "") and string.format("track '%s'", r.track)
      or (r.slot_id and string.format("AAF slot %d", r.slot_id)) or nil
    local where = label and (label .. (r.start and (" at " .. hms(tc_start + r.start)) or "")) or nil
    local it = r.ev and self.item_of[r.ev]
    local tname = (r.track and r.track ~= "") and r.track or (r.slot_id and ("AAF slot " .. r.slot_id)) or nil
    self:problem(where, r.message, r.start and (tc_start + r.start - offset) or nil, it, it and it.track or tname)
  end

  self.tl, self.comp, self.plan, self.track_fx = tl, comp, plan, track_fx
  self.tc_start, self.offset = tc_start, offset
  self.ok = true
  return self
end

-- Stage 2. Extract embedded media for up to `budget` seconds of `clock()`
-- (math.huge for all of it), writing `step_bytes` (default 1 MB) at a time.
-- Returns true when every file is done.
-- Progress: job.done_bytes of job.total_bytes; job.task_index of #job.tasks.
function builder.extract_step(job, budget, clock, step_bytes)
  clock = clock or os.clock
  step_bytes = step_bytes or (1 << 20)
  local t0 = clock()
  while job.task_index <= #job.tasks do
    local task = job.tasks[job.task_index]
    if not task.err and not task.path then
      if not task.writer then job:start_task(task) end
      if task.writer then
        local before = task.writer.done
        local finished = task.writer:step(step_bytes)
        job.done_bytes = job.done_bytes + (task.writer.done - before)
        if finished then job:finish_task(task) end
      end
    end
    if task.err or task.path then
      job.task_index = job.task_index + 1
    end
    if clock() - t0 >= budget then break end
  end
  return job.task_index > #job.tasks
end

-- Problems that have a place on the timeline, for the marker question.
function builder.positioned_problems(job)
  local n = 0
  for _, p in ipairs(job.problems) do
    if p.pos and p.pos >= 0 then n = n + 1 end
  end
  return n
end

-- Give up: delete the partial file, close the AAF. The project is untouched;
-- finished files stay in the media folder and are reused next time.
function builder.cancel(job)
  local task = job.tasks and job.tasks[job.task_index]
  if task and task.writer then task.writer:abort() end
  if job.file then job.file:close() job.file = nil end
end

-- Stage 3. `opts.markers`: add a marker at each problem with a timeline
-- position. Returns { ok, report, counts, problems, needs_attention } or
-- { ok = false, message }.
function builder.finish(job, opts)
  opts = opts or {}
  local ok, result = pcall(Import.build, job, opts)
  if job.file then job.file:close() job.file = nil end
  if not ok then return stop("The import failed:\n" .. tostring(result)) end
  return result
end

function Import:build(opts)
  local api, proj, tl = self.api, self.proj, self.tl
  local tc_start, offset = self.tc_start, self.offset
  -- The project may have changed while extraction ran.
  local cur, curfn = api.EnumProjects(-1)
  if cur ~= proj or curfn ~= self.projfn then
    return stop("The project changed during the import, so nothing was added. The extracted files are kept in " ..
      "the media folder and will be reused if you import again.")
  end
  if math.abs(api.GetProjectTimeOffset(proj, false) - offset) > 1e-9 then
    return stop("The project start time changed during the import, so nothing was added. Import again.")
  end
  -- Items whose embedded media couldn't be extracted are skipped.
  for ti in ipairs(tl.tracks) do
    local kept = {}
    for _, it in ipairs(self.plan[ti]) do
      if it.task then
        if it.task.path then
          it.path = it.task.path
          if it.name == "" then it.name = basename(it.path) end
        else
          self:problem(it.where, "clip skipped: its embedded audio could not be extracted: " .. tostring(it.task.err), it.pos, nil, it.track)
          self.count.skipped = self.count.skipped + 1
          it = nil
        end
      end
      if it then kept[#kept + 1] = it end
    end
    self.plan[ti] = kept
  end
  local plan, track_fx, comp = self.plan, self.track_fx, self.comp
  local imp = self

  -- Build, in one undo block.
  api.Undo_BeginBlock2(proj)
  api.PreventUIRefresh(1)
  local base = api.CountTracks(proj)
  for ti, t in ipairs(tl.tracks) do
    local idx = base + ti - 1
    api.InsertTrackAtIndex(idx, false)
    local tr = api.GetTrack(proj, idx)
    local name = t.name
    if not name or name == "" then name = "Track " .. tostring(t.track_number or ti) end
    api.GetSetMediaTrackInfo_String(tr, "P_NAME", name, true)
    local tfx = track_fx[ti]
    if tfx.vol ~= 1 then api.SetMediaTrackInfo_Value(tr, "D_VOL", tfx.vol) end
    if tfx.pan then api.SetMediaTrackInfo_Value(tr, "D_PAN", tfx.pan) end
    -- Track envelopes (VOLENV2, PANENV2: observed), written into the new,
    -- still empty track's state chunk, over the track's whole length.
    local blocks = {}
    local t_end = t.length and rnum(rdiv(edit.R(t.length), t.rate)) + tc_start - offset or 0
    if #tfx.gains > 0 then
      local w0 = math.max(0, tc_start - offset)
      blocks[#blocks + 1] = envelope_block("VOLENV2", envelope_points(tfx.gains, w0, math.max(t_end, w0),
        function(x) return x end, function(a, b) return a * b end), true)
    end
    if tfx.pan_curve then
      local w0 = math.max(0, tc_start - offset)
      blocks[#blocks + 1] = envelope_block("PANENV2", envelope_points({ tfx.pan_curve }, w0, math.max(t_end, w0),
        pan_env_value), false)
    end
    if #blocks > 0 then
      local _, chunk = api.GetTrackStateChunk(tr, "", false)
      local new = chunk and add_to_chunk(chunk, blocks)
      if new and api.SetTrackStateChunk(tr, new, false) then
        imp.count.envelopes = imp.count.envelopes + #blocks
      else
        imp:problem(string.format("track %d", ti), "track automation could not be written")
      end
    end
    imp.count.tracks = imp.count.tracks + 1
    for _, it in ipairs(plan[ti]) do
      local item = api.AddMediaItemToTrack(tr)
      it.item = item
      local take = api.AddTakeToMediaItem(item)
      local src = api.PCM_Source_CreateFromFile(it.path)
      api.SetMediaItemTake_Source(take, src)
      api.SetMediaItemInfo_Value(item, "D_POSITION", it.pos)
      api.SetMediaItemInfo_Value(item, "D_LENGTH", it.length)
      api.SetMediaItemInfo_Value(item, "B_LOOPSRC", 0)
      api.SetMediaItemTakeInfo_Value(take, "D_STARTOFFS", it.startoffs)
      if it.chanmode then api.SetMediaItemTakeInfo_Value(take, "I_CHANMODE", it.chanmode) end
      if it.vol ~= 1 then api.SetMediaItemInfo_Value(item, "D_VOL", it.vol) end
      if it.pan then api.SetMediaItemTakeInfo_Value(take, "D_PAN", it.pan) end
      -- Fades are linear (shape 0), as Pro Tools' import shows them.
      if it.fade_in and it.fade_in > 0 then
        api.SetMediaItemInfo_Value(item, "D_FADEINLEN", it.fade_in)
        api.SetMediaItemInfo_Value(item, "C_FADEINSHAPE", 0)
        api.SetMediaItemInfo_Value(item, "D_FADEINDIR", 0)
      end
      if it.fade_out and it.fade_out > 0 then
        api.SetMediaItemInfo_Value(item, "D_FADEOUTLEN", it.fade_out)
        api.SetMediaItemInfo_Value(item, "C_FADEOUTSHAPE", 0)
        api.SetMediaItemInfo_Value(item, "D_FADEOUTDIR", 0)
      end
      -- Take envelopes (VOLENV, PANENV: observed), times from the item start.
      local blocks = {}
      if it.vol_env then blocks[#blocks + 1] = envelope_block("VOLENV", it.vol_env, true) end
      if it.pan_env then blocks[#blocks + 1] = envelope_block("PANENV", it.pan_env, false) end
      if #blocks > 0 then
        local _, chunk = api.GetItemStateChunk(item, "", false)
        local new = chunk and add_to_chunk(chunk, blocks)
        if new and api.SetItemStateChunk(item, new, false) then
          imp.count.envelopes = imp.count.envelopes + #blocks
        else
          imp:problem(it.where, "clip automation could not be written", it.pos, it, it.track)
        end
      end
      api.GetSetMediaItemTakeInfo_String(take, "P_NAME", it.name, true)
      imp.count.clips = imp.count.clips + 1
    end
  end
  for _, m in ipairs(tl.markers) do
    local pos = tc_start + m.start - offset
    if pos >= 0 then
      api.AddProjectMarker2(proj, false, pos, 0, m.comment or "", -1, 0)
      imp.count.markers = imp.count.markers + 1
    else
      imp:problem(nil, "marker before project zero skipped: " .. tostring(m.comment))
    end
  end
  -- Marking problems, if asked for (section 5): a marker at each, naming
  -- the track and clip; each problem clip coloured red, with a note saying
  -- what's wrong.
  if opts.markers then
    local red = api.ColorToNative(220, 40, 40) | 0x1000000
    local notes = {}
    for _, p in ipairs(imp.problems) do
      if p.pos and p.pos >= 0 then
        local who = p.track or ""
        if p.it and p.it.name and p.it.name ~= "" then who = (who ~= "" and (who .. ", ") or "") .. p.it.name end
        local name = "AAF: " .. (who ~= "" and (who .. ": ") or "") .. p.message
        if #name > 160 then name = name:sub(1, 157) .. "..." end
        api.AddProjectMarker2(proj, false, p.pos, 0, name, -1, 0)
        imp.count.problem_markers = (imp.count.problem_markers or 0) + 1
      end
      local item = p.it and p.it.item
      if item then
        if not notes[item] then
          notes[item] = {}
          api.SetMediaItemInfo_Value(item, "I_CUSTOMCOLOR", red)
          imp.count.problem_items = (imp.count.problem_items or 0) + 1
        end
        table.insert(notes[item], "AAF import: " .. p.message)
      end
    end
    for item, lines in pairs(notes) do
      api.GetSetMediaItemInfo_String(item, "P_NOTES", table.concat(lines, "\n"), true)
    end
  end
  api.PreventUIRefresh(-1)
  api.UpdateArrange()
  api.Undo_EndBlock2(proj, "Import AAF", -1)

  return { ok = true, report = imp:report_text(tl, comp), counts = imp.count, problems = imp.problems,
           needs_attention = #imp.problems > 0 }
end

-- The whole import in one go: prepare, extract everything, finish.
-- `opts` as for prepare, plus `markers` as for finish.
function builder.run(api, opts)
  local job = builder.prepare(api, opts)
  if not job.ok then return job end
  local ok, err = pcall(builder.extract_step, job, math.huge)
  if not ok then
    builder.cancel(job)
    return stop("The import failed:\n" .. tostring(err))
  end
  return builder.finish(job, { markers = opts.markers })
end

