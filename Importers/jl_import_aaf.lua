-- Effects (recorded for milestone 4)

-- An OperationGroup's operation and parameters, and the span it covers:
-- `pos` and `length` in the track's edit units. Parameter values are
-- layer 2's decoded Indirect values ({ indirect = type name, value }).
-- VaryingValue times are fractions of the span (MS-01 6.18).
local function effect_of(og, pos, length, param_names)
  local op = og:get("Operation")
  local e = {
    id = is_object(op) and op:get("Identification") or nil,
    name = is_object(op) and op:get("Name") or nil,
    inputs = #(og:get("InputSegments") or {}),
    params = {}, pos = pos, length = length,
  }
  for _, p in ipairs(og:get("Parameters") or {}) do
    local pid = p:get("Definition")
    local par = { id = pid, name = pid and param_names and param_names[pid] or nil, class = p:class_name() }
    if p:is_a("ConstantValue") then
      par.kind = "constant"
      par.value = p:get("Value")
    elseif p:is_a("VaryingValue") then
      par.kind = "varying"
      local interp = p:get("Interpolation")
      par.interpolation = is_object(interp) and interp:get("Identification") or nil
      par.interpolation_name = is_object(interp) and interp:get("Name") or nil
      par.points = {}
      for i, cp in ipairs(p:get("PointList") or {}) do
        local t = cp:get("Time")
        par.points[i] = { time = t and R(t.Numerator, t.Denominator) or nil, value = cp:get("Value") }
      end
    else
      par.kind = "unknown"
    end
    e.params[#e.params + 1] = par
  end
  return e
end
edit.effect_of = effect_of

