-- Timeline

-- Walk a segment of an audio track. `pos` is the segment's start in the
-- track's edit units (integer); `effects` the enclosing effects, outermost
-- first. Appends to track.events and track.crossfades; returns the events
-- this segment produced (for linking crossfades).
function Context:_walk(track, seg, pos, effects, depth)
  local produced = {}
  if depth > 64 then
    self:_report(track, pos, "nesting too deep; skipped " .. seg:class_name())
    return produced
  end
  local len = seg:get("Length")
  if len == nil then
    self:_report(track, pos, seg:class_name() .. " has no Length; treated as 0")
    len = 0
  end

  if seg:is_a("SourceClip") then
    local ev = {
      pos = pos, length = len, clip = seg, effects = effects,
      start = seconds(pos, track.rate), duration = seconds(len, track.rate),
      channel = (seg:get("ChannelIDs") or {})[1],
    }
    -- MS-01 7.7: deprecated fade properties, kept if a writer uses them.
    local fil, fol = seg:get("FadeInLength"), seg:get("FadeOutLength")
    if fil or fol then
      ev.fade_in = fil and { length = fil, type = seg:get("FadeInType") } or nil
      ev.fade_out = fol and { length = fol, type = seg:get("FadeOutType") } or nil
    end
    local src, why, hops = self:resolve(seg, track.rate, R(0))
    ev.hops = hops
    if src then
      ev.source = src
      -- Does the clip run past the end of what it points at?
      if src.room and rlt(src.room, rdiv(R(len), track.rate)) then
        self:_report(track, pos, "clip runs past the end of its source media", ev)
        ev.short_source = true
      end
    else
      ev.unresolved = why
      self:_report(track, pos, "clip source not found: " .. why, ev)
    end
    track.events[#track.events + 1] = ev
    produced[1] = ev
    return produced
  end

  if seg:is_a("Filler") then return produced end

  if seg:is_a("Sequence") then
    local p = pos
    local pending = nil       -- a crossfade waiting for its following events
    local last = {}           -- events of the previous segment
    for _, sub in ipairs(seg:get("Components") or {}) do
      local sl = sub:get("Length") or 0
      if sub:is_a("Transition") then
        -- MS-01 7.2, 7.4: overlaps the neighbouring segments.
        p = p - sl
        local og = sub:get("OperationGroup")
        local xf = {
          pos = p, length = sl, start = seconds(p, track.rate), duration = seconds(sl, track.rate),
          cut_point = sub:get("CutPoint"), effect = is_object(og) and effect_of(og, p, sl, self.param_names) or nil,
          before = last[#last],
        }
        track.crossfades[#track.crossfades + 1] = xf
        pending = xf
      else
        local got = self:_walk(track, sub, p, effects, depth + 1)
        if pending then
          pending.after = got[1]
          pending = nil
        end
        last = got
        for _, e in ipairs(got) do produced[#produced + 1] = e end
        p = p + sl
      end
    end
    return produced
  end

  if seg:is_a("OperationGroup") then
    local inputs = seg:get("InputSegments") or {}
    local eff = effect_of(seg, pos, len, self.param_names)
    if #inputs == 1 then
      local inner = {}
      for i, e in ipairs(effects) do inner[i] = e end
      inner[#inner + 1] = eff
      return self:_walk(track, inputs[1], pos, inner, depth + 1)
    end
    self:_report(track, pos, string.format("operation '%s' with %d inputs skipped", tostring(eff.name or aaf.auid_string(eff.id or "")), #inputs))
    return produced
  end

  if seg:is_a("Selector") then
    local sel = seg:get("Selected")                 -- MS-01 7.20
    if is_object(sel) then return self:_walk(track, sel, pos, effects, depth + 1) end
  elseif seg:is_a("NestedScope") then
    local slots = seg:get("Slots") or {}            -- MS-01 7.18: the last slot is the value
    if is_object(slots[#slots]) then return self:_walk(track, slots[#slots], pos, effects, depth + 1) end
  end

  self:_report(track, pos, seg:class_name() .. " not handled; skipped")
  return produced
end

function Context:_report(track, pos, message, ev)
  local r = {
    track = track and track.name, slot_id = track and track.slot_id,
    pos = pos, start = track and pos and seconds(pos, track.rate) or nil, message = message,
    ev = ev,
  }
  self.report[#self.report + 1] = r
end

-- Timecode start (brief section 5, layer 3): the Timecode segment's Start
-- is a frame count; FPS is the nominal rate, so the slot's edit rate is
-- what converts it to seconds.
local function timecode_of(slot)
  local seg = slot:get("Segment")
  local rate = rate_of(slot:get("EditRate"))
  if is_object(seg) and seg:is_a("Sequence") then
    for _, c in ipairs(seg:get("Components") or {}) do
      if c:is_a("Timecode") then seg = c break end
    end
  end
  if not (is_object(seg) and seg:is_a("Timecode") and rate) then return nil end
  local start = seg:get("Start") or 0
  return {
    slot_id = slot:get("SlotID"), start = start, fps = seg:get("FPS"), drop = seg:get("Drop"),
    rate = rate, seconds = seconds(start, rate),
  }
end

-- Markers from EventMobSlots (MS-01 6.12, 7.8): absolute Positions in the
-- slot's edit units.
local function markers_of(slot, out)
  local rate = rate_of(slot:get("EditRate"))
  local seg = slot:get("Segment")
  local list = {}
  if is_object(seg) and seg:is_a("Sequence") then list = seg:get("Components") or {} else list = { seg } end
  for _, ev in ipairs(list) do
    if is_object(ev) and ev:is_a("Event") and rate then
      local p = ev:get("Position") or 0
      out[#out + 1] = {
        slot_id = slot:get("SlotID"), pos = p, start = seconds(p, rate), rate = rate,
        length = ev:get("Length"), comment = ev:get("Comment"), class = ev:class_name(),
      }
    end
  end
end

-- The timeline of composition `mob`.
function edit.timeline(file, mob)
  local ctx = new_context(file)
  ctx.report = {}
  local tl = {
    name = mob:get("Name"), mobid = mob:get("MobID"),
    tracks = {}, markers = {}, report = ctx.report, timecode = nil,
  }
  for _, slot in ipairs(mob:get("Slots") or {}) do
    local seg = slot:get("Segment")
    local kind = is_object(seg) and data_kind(seg) or "unknown"
    local rate = rate_of(slot:get("EditRate"))
    local label = { name = slot:get("SlotName"), slot_id = slot:get("SlotID") }
    if slot:is_a("EventMobSlot") then
      markers_of(slot, tl.markers)
    elseif not slot:is_a("TimelineMobSlot") then
      ctx:_report(label, nil, slot:class_name() .. " skipped")
    elseif kind == "timecode" then
      local tc = timecode_of(slot)
      if tc and not tl.timecode then tl.timecode = tc
      elseif not tc then ctx:_report(label, nil, "timecode track without a readable Timecode segment")
      end
    elseif kind ~= "sound" then
      ctx:_report(label, nil, string.format("%s track skipped", kind))
    elseif not rate then
      ctx:_report(label, nil, "audio track without an edit rate skipped")
    else
      local track = {
        name = slot:get("SlotName"), slot_id = slot:get("SlotID"),
        track_number = slot:get("PhysicalTrackNumber"), rate = rate,
        origin = slot:get("Origin") or 0, length = is_object(seg) and seg:get("Length") or 0,
        events = {}, crossfades = {}, effects = {},
      }
      if track.origin ~= 0 then
        ctx:_report(track, nil, "composition track has a non-zero Origin; positions are not adjusted for it")
      end
      -- Track-level effects (AS-01 12.17.3, 12.18.3): single-input
      -- OperationGroups directly under the slot, around the whole track.
      while is_object(seg) and seg:is_a("OperationGroup") and #(seg:get("InputSegments") or {}) == 1 do
        track.effects[#track.effects + 1] = effect_of(seg, 0, seg:get("Length") or 0, ctx.param_names)
        seg = seg:get("InputSegments")[1]
      end
      if is_object(seg) then ctx:_walk(track, seg, 0, {}, 0) end
      tl.tracks[#tl.tracks + 1] = track
    end
  end
  table.sort(tl.markers, function(a, b) return a.start < b.start end)
  return tl
end

return edit

end

package.preload["essence"] = function(...)
-- essence.lua: embedded audio essence to a real little-endian WAV file.
--
-- Brief 3.4 and 4.2: whatever the essence was inside the AAF, it becomes a
-- WAV; integer PCM stays integer and float stays float; 8-bit AIFF audio is
-- signed and 8-bit WAV unsigned, so it is sign-flipped, not byte-swapped;
-- a sample format not recognized here is reported, never guessed.
--
-- Three stream layouts are recognized:
--   AIFF / AIFF-C (brief 4.2): IFF chunks, each a 4-character id and a
--     big-endian 32-bit size, padded to an even length. COMM holds channels,
--     frame count, bit depth, the sample rate as an 80-bit IEEE extended
--     float and, in AIFF-C only, a compression type: NONE is big-endian PCM,
--     sowt is little-endian PCM. SSND holds an offset and a block size, then
--     the data.
--   RIFF WAVE (MS-01 11.1, which defers to the Microsoft/IBM Multimedia
--     Programming Interface and Data Specifications 1.0): little-endian
--     chunks; "fmt " holds the format tag (1 integer PCM, 3 IEEE float),
--     channels, sample rate and bits; "data" holds the samples. Tag 0xFFFE
--     (WAVE_FORMAT_EXTENSIBLE, Microsoft) carries the real tag in the first
--     two bytes of its SubFormat.
--   Headerless PCM (MS-01 13.2): no header; the format comes from the file
--     SourceMob's PCMDescriptor, and the data is BWF, so little-endian.
--
-- Data is copied in chunks aligned to whole sample frames, converted with
-- string routines (gsub) rather than a per-sample loop.

local essence = {}

local CHUNK_BYTES = 1 << 20

-- 80-bit IEEE 754 extended precision, big-endian: sign and 15-bit exponent
-- (bias 16383), then a 64-bit mantissa with an explicit integer bit.
local function extended_to_number(b)
  local se, hi, lo = string.unpack(">I2I4I4", b)
  local sign = (se & 0x8000) ~= 0 and -1 or 1
  local exp = se & 0x7FFF
  if exp == 0 and hi == 0 and lo == 0 then return 0 end
  local mant = hi * 4294967296.0 + lo
  return sign * mant * 2.0 ^ (exp - 16383 - 63)
end
essence.extended_to_number = extended_to_number

-- gsub pattern pairs that reverse the byte order of one sample.
local SWAP = {
  [2] = { "(.)(.)", "%2%1" },
  [3] = { "(.)(.)(.)", "%3%2%1" },
  [4] = { "(.)(.)(.)(.)", "%4%3%2%1" },
  [8] = { "(.)(.)(.)(.)(.)(.)(.)(.)", "%8%7%6%5%4%3%2%1" },
}

local function supported_width(bytes) return bytes == 1 or SWAP[bytes] ~= nil end

-- Clip the data to whole frames the stream actually holds; `want` is what
-- the header or descriptor promises, if it says.
local function settle(fmt, size, want)
  fmt.block_align = fmt.sample_bytes * fmt.channels
  local have = math.max(0, math.min(fmt.data_bytes, size - fmt.data_start))
  have = have - have % fmt.block_align
  want = want or have
  fmt.data_bytes = math.min(want, have)
  fmt.short = fmt.data_bytes < want
  fmt.frames = fmt.data_bytes // fmt.block_align
  return fmt
end

-- AIFF / AIFF-C header through `read(offset, length)`.
function essence.parse_aiff(read, size)
  local head = read(0, 12)
  if #head < 12 or head:sub(1, 4) ~= "FORM" then return nil, "not an IFF FORM" end
  local kind = head:sub(9, 12)
  if kind ~= "AIFF" and kind ~= "AIFC" then return nil, "FORM type " .. kind .. " is not AIFF or AIFC" end
  local fmt = { container = kind }
  local frames
  local pos = 12
  while pos + 8 <= size do
    local ch = read(pos, 8)
    local id, len = ch:sub(1, 4), string.unpack(">I4", ch, 5)
    if id == "COMM" then
      local c = read(pos + 8, len)
      fmt.channels, frames, fmt.bits = string.unpack(">i2I4i2", c)
      fmt.rate = extended_to_number(c:sub(9, 18))
      fmt.compression = kind == "AIFC" and c:sub(19, 22) or "NONE"
    elseif id == "SSND" then
      local offset = string.unpack(">I4", read(pos + 8, 4))
      fmt.data_start = pos + 16 + offset
      fmt.data_bytes = len - 8 - offset
    end
    pos = pos + 8 + len + (len % 2)
  end
  if not fmt.channels then return nil, "no COMM chunk" end
  if not fmt.data_start then return nil, "no SSND chunk" end
  local c = fmt.compression
  local bytes = (fmt.bits + 7) // 8
  if c == "NONE" then
    fmt.float, fmt.big_endian = false, true
  elseif c == "sowt" then
    fmt.float, fmt.big_endian = false, false
  elseif c == "fl32" or c == "FL32" then
    fmt.float, fmt.big_endian, bytes = true, true, 4
  elseif c == "fl64" or c == "FL64" then
    fmt.float, fmt.big_endian, bytes = true, true, 8
  else
    return nil, "unsupported AIFF-C compression '" .. c .. "'"
  end
  if not supported_width(bytes) then return nil, string.format("unsupported sample size %d bits", fmt.bits) end
  fmt.sample_bytes = bytes
  fmt.bits = bytes * 8
  -- 8-bit AIFF is signed; WAV is unsigned (brief 3.4).
  fmt.sign_flip = bytes == 1 and not fmt.float
  return settle(fmt, size, frames * bytes * fmt.channels)
end

-- RIFF WAVE header.
function essence.parse_riff(read, size)
  local head = read(0, 12)
  if #head < 12 or head:sub(1, 4) ~= "RIFF" or head:sub(9, 12) ~= "WAVE" then return nil, "not a RIFF WAVE" end
  local fmt = { container = "WAVE", big_endian = false }
  local tag
  local pos = 12
  while pos + 8 <= size do
    local ch = read(pos, 8)
    local id, len = ch:sub(1, 4), string.unpack("<I4", ch, 5)
    if id == "fmt " then
      local c = read(pos + 8, len)
      local rate
      tag, fmt.channels, rate, _, _, fmt.bits = string.unpack("<I2I2I4I4I2I2", c)
      fmt.rate = rate
      if tag == 0xFFFE and #c >= 26 then tag = string.unpack("<I2", c, 25) end
    elseif id == "data" then
      fmt.data_start = pos + 8
      fmt.data_bytes = len
    end
    pos = pos + 8 + len + (len % 2)
  end
  if not tag then return nil, "no fmt chunk" end
  if not fmt.data_start then return nil, "no data chunk" end
  if tag == 1 then
    fmt.float, fmt.compression = false, "PCM"
  elseif tag == 3 then
    fmt.float, fmt.compression = true, "float"
  else
    return nil, string.format("unsupported WAVE format tag %d", tag)
  end
  local bytes = (fmt.bits + 7) // 8
  if not supported_width(bytes) then return nil, string.format("unsupported sample size %d bits", fmt.bits) end
  fmt.sample_bytes = bytes
  fmt.bits = bytes * 8
  return settle(fmt, size, nil)
end

-- Headerless PCM from a PCMDescriptor. MS-01 13.1 conditional rule 1:
-- uncompressed essence omits Compression, so a Compression value is refused
-- rather than guessed at.
-- `desc` = { channels, bits, rate, block_align, frames, compression }.
function essence.parse_pcm(desc, size)
  if desc.compression ~= nil then return nil, "compressed PCMDescriptor essence is not supported" end
  if not (desc.channels and desc.bits and desc.rate) then return nil, "PCMDescriptor lacks channels, bits or rate" end
  local bytes = (desc.bits + 7) // 8
  if not supported_width(bytes) then return nil, string.format("unsupported sample size %d bits", desc.bits) end
  if desc.block_align and desc.block_align ~= bytes * desc.channels then
    return nil, string.format("block align %d does not match %d channels of %d bits", desc.block_align, desc.channels, desc.bits)
  end
  local fmt = {
    container = "PCM", compression = "none", channels = desc.channels, bits = bytes * 8,
    rate = desc.rate, float = false, big_endian = false, sample_bytes = bytes,
    data_start = 0, data_bytes = size,
  }
  return settle(fmt, size, desc.frames and desc.frames * bytes * desc.channels or nil)
end

-- WAV header for the given format and data size. Float uses format tag 3
-- with a fact chunk; integer PCM uses tag 1.
local function wav_header(fmt, data_bytes)
  local rate = math.floor(fmt.rate + 0.5)
  local tag = fmt.float and 3 or 1
  local fmt_chunk = string.pack("<I2I2I4I4I2I2", tag, fmt.channels, rate,
    rate * fmt.block_align, fmt.block_align, fmt.sample_bytes * 8)
  local fact = ""
  if fmt.float then fact = "fact" .. string.pack("<I4I4", 4, data_bytes // fmt.block_align) end
  local riff_size = 4 + (8 + #fmt_chunk) + #fact + (8 + data_bytes) + (data_bytes % 2)
  return "RIFF" .. string.pack("<I4", riff_size) .. "WAVE"
    .. "fmt " .. string.pack("<I4", #fmt_chunk) .. fmt_chunk
    .. fact
    .. "data" .. string.pack("<I4", data_bytes)
end

local SIGN_FLIP = {}
for b = 0, 255 do SIGN_FLIP[string.char(b)] = string.char(b ~ 0x80) end

local function convert(fmt, data)
  if fmt.sign_flip then return (data:gsub(".", SIGN_FLIP)) end
  if not fmt.big_endian or fmt.sample_bytes == 1 then return data end
  local p = SWAP[fmt.sample_bytes]
  return (data:gsub(p[1], p[2]))
end

-- Identify the stream's layout. `desc` (optional) describes headerless PCM,
-- as in parse_pcm; it is used only when the stream has no AIFF or RIFF
-- header.
function essence.parse(read, size, desc)
  local magic = size >= 4 and read(0, 4) or ""
  if magic == "FORM" then return essence.parse_aiff(read, size) end
  if magic == "RIFF" then return essence.parse_riff(read, size) end
  if desc then return essence.parse_pcm(desc, size) end
  return nil, "unrecognized essence: no AIFF or WAVE header and no PCM descriptor"
end

-- An incremental writer of the essence as a WAV at `out_path`, so a large
-- extraction can be spread across REAPER's defer cycles:
--   local w = essence.writer(read, size, desc, path)
--   repeat until w:step(bytes)   -- true once everything is written
--   w:abort()                    -- stop and delete the partial file
-- `read(offset, length)` reads the essence stream. Returns the writer, or
-- nil and a reason. w.fmt is the format; w.done and w.total count bytes.
function essence.writer(read, size, desc, out_path)
  local fmt, err = essence.parse(read, size, desc)
  if not fmt then return nil, err end
  local out, oerr = io.open(out_path, "wb")
  if not out then return nil, oerr end
  out:write(wav_header(fmt, fmt.data_bytes))
  local chunk = CHUNK_BYTES - CHUNK_BYTES % fmt.block_align
  local w = { fmt = fmt, done = 0, total = fmt.data_bytes }
  function w:step(max_bytes)
    local budget = max_bytes or math.huge
    while self.done < fmt.data_bytes and budget > 0 do
      -- Whole frames, at least one, within the budget.
      local allowed = math.max(fmt.block_align, budget - budget % fmt.block_align)
      local n = math.min(chunk, fmt.data_bytes - self.done, allowed)
      out:write(convert(fmt, read(fmt.data_start + self.done, n)))
      self.done = self.done + n
      budget = budget - n
    end
    if self.done < fmt.data_bytes then return false end
    if out then
      if fmt.data_bytes % 2 == 1 then out:write("\0") end
      out:close()
      out = nil
    end
    return true
  end
  function w:abort()
    if out then out:close() out = nil end
    os.remove(out_path)
  end
  return w
end

-- Write the essence as a WAV at `out_path` in one go. Returns the format
-- table, or nil and a reason.
function essence.to_wav(read, size, desc, out_path)
  local w, err = essence.writer(read, size, desc, out_path)
  if not w then return nil, err end
  w:step()
  return w.fmt
end

return essence

end

package.preload["effects"] = function(...)
-- effects.lua: recognizes the audio effects the edit layer records, and
-- reads their parameters as curves.
--
-- Effects are recognized by ID first, then by the names AS-01 gives them
-- (brief section 1: Jon's decision, September 2026). No specification lists
-- the IDs; each below was observed, and in Premiere's files the same ID
-- carries the AS-01 name shown. Pro Tools writes the same IDs with blank
-- names.

local aaf = require("aaf")

local effects = {}

-- An AUID's text form (as aaf.auid_string prints it) to its key.
local function auid(text)
  local d1, d2, d3, d4 = text:match("^(%x+)%-(%x+)%-(%x+)%-(%x+%-%x+)$")
  d4 = d4:gsub("%-", "")
  local tail = d4:gsub("%x%x", function(h) return string.char(tonumber(h, 16)) end)
  return string.pack("<I4I2I2", tonumber(d1, 16), tonumber(d2, 16), tonumber(d3, 16)) .. tail
end
effects.auid = auid

-- Operations. Observed IDs; the AS-01 section defining each by name.
local OPERATIONS = {
  { kind = "gain", name = "Mono Audio Gain",               -- AS-01 12.17.1
    id = auid("9d2ea894-0968-11d3-8a38-0050040ef7d2") },
  { kind = "pan", name = "Mono Audio Pan",                 -- AS-01 12.18.1
    id = auid("9d2ea893-0968-11d3-8a38-0050040ef7d2") },
  { kind = "dissolve", name = "Mono Audio Dissolve",       -- AS-01 12.19.1
    id = auid("0c3bea41-fc05-11d2-8a29-0050040ef7d2") },
  { kind = "dissolve2", name = "Two-Parameter Mono Audio Dissolve" },  -- AS-01 12.20.1; ID not observed
}

-- Parameters. Observed IDs; AS-01 names.
local PARAMETERS = {
  { kind = "amplitude", name = "Amplitude multiplier",     -- AS-01 12.17.2
    id = auid("e4962321-2267-11d3-8a4c-0050040ef7d2") },
  { kind = "pan", name = "Pan value",                      -- AS-01 12.18.2
    id = auid("e4962322-2267-11d3-8a4c-0050040ef7d2") },
  { kind = "level", name = "Level",                        -- AS-01 12.19.2
    id = auid("e4962320-2267-11d3-8a4c-0050040ef7d2") },
  { kind = "outgoing", name = "Outgoing Level" },          -- AS-01 12.20.2; ID not observed
  { kind = "incoming", name = "Incoming Level" },          -- AS-01 12.20.3; ID not observed
}

-- Interpolations (MS-01 8.6 defines the class; these are observed IDs,
-- which Premiere names LinearInterp and PowerInterp).
local INTERP_LINEAR = auid("5b6c85a4-0ede-11d3-80a9-006008143e6f")

local function lookup(table_, id, name)
  if id then
    for _, e in ipairs(table_) do
      if e.id and e.id == id then return e.kind end
    end
  end
  if name and name ~= "" then
    for _, e in ipairs(table_) do
      if e.name == name then return e.kind end
    end
  end
  return nil
end

-- "gain", "pan", "dissolve", "dissolve2" or nil.
function effects.kind(e)
  return lookup(OPERATIONS, e.id, e.name)
end

-- The parameter of `e` of the given kind, or nil.
function effects.param(e, kind)
  for _, p in ipairs(e.params or {}) do
    if lookup(PARAMETERS, p.id, p.name) == kind then return p end
  end
  return nil
end

-- A decoded parameter value (layer 2's Indirect) as a number.
function effects.number(v)
  if type(v) ~= "table" or not v.indirect then return nil end
  local x = v.value
  if type(x) == "number" then return x end
  if type(x) == "table" and x.Numerator and x.Denominator and x.Denominator ~= 0 then
    return x.Numerator / x.Denominator
  end
  return nil
end

-- A parameter as a curve: { constant = value } or
-- { points = { { t, v } ... }, linear = bool }, with t a fraction of the
-- effect's span (MS-01 6.18). nil if its values can't be read.
function effects.curve(p)
  if not p then return nil end
  if p.kind == "constant" then
    local v = effects.number(p.value)
    return v and { constant = v } or nil
  end
  if p.kind ~= "varying" then return nil end
  local pts = {}
  for _, cp in ipairs(p.points or {}) do
    local v = effects.number(cp.value)
    if v == nil or not cp.time then return nil end
    pts[#pts + 1] = { t = cp.time.n / cp.time.d, v = v }
  end
  if #pts == 0 then return nil end
  return { points = pts, linear = p.interpolation == nil or p.interpolation == INTERP_LINEAR }
end

-- Value of a curve at t (MS-01 6.18: linear between points; held
-- constant before the first and after the last; where points share a time,
-- the last one applies from then on).
function effects.value_at(c, t)
  if c.constant then return c.constant end
  local pts = c.points
  if t <= pts[1].t then return pts[1].v end
  for i = 2, #pts do
    local a, b = pts[i - 1], pts[i]
    if t < b.t then
      if b.t == a.t then return b.v end
      return a.v + (b.v - a.v) * (t - a.t) / (b.t - a.t)
    end
  end
  return pts[#pts].v
end

-- The curve's single value over the samples that play, if it has one.
-- A span of `units` edit units plays from t = 0 to t = (units - 1)/units;
-- a change at t = 1 (as Pro Tools writes at a clip's end) never sounds.
function effects.flat_value(c, units)
  if c.constant then return c.constant end
  local last = units > 1 and (units - 1) / units or 0
  local v0 = effects.value_at(c, 0)
  local times = { last }
  for _, p in ipairs(c.points) do
    if p.t > 0 and p.t < last then times[#times + 1] = p.t end
  end
  for _, t in ipairs(times) do
    if math.abs(effects.value_at(c, t) - v0) > 1e-9 then return nil end
  end
  return v0
end

-- True if all of a curve's values are equal: Premiere writes dissolve
-- Levels of 0 at both ends, which is read as the AS-01 default instead
-- (Jon's decision, September 2026).
function effects.degenerate(c)
  if c.constant then return true end
  for _, p in ipairs(c.points) do
    if math.abs(p.v - c.points[1].v) > 1e-9 then return false end
  end
  return true
end

-- A readable name for reports.
function effects.label(e)
  local k = effects.kind(e)
  if k then
    for _, o in ipairs(OPERATIONS) do if o.kind == k then return o.name end end
  end
  if e.name and e.name ~= "" then return e.name end
  return e.id and ("effect " .. aaf.auid_string(e.id)) or "unnamed effect"
end

return effects

end

package.preload["builder"] = function(...)
-- builder.lua: layer 4 of jl_import_aaf. Builds the edit layer's timeline
-- (edit.lua) into the REAPER project: extracts or locates media, then
-- creates tracks and items in one undo block.
--
-- Every REAPER call goes through `api`, the reaper table in REAPER and a
-- mock in tests (tests/mock_reaper.lua). Files are real in both.
--
-- Order (brief section 5, layer 4): check the project, read the AAF, check
