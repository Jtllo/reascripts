-- Small helpers

local function exists(path)
  local fh = io.open(path, "rb")
  if fh then fh:close() return true end
  return false
end

local function file_size(path)
  local fh = io.open(path, "rb")
  if not fh then return nil end
  local n = fh:seek("end")
  fh:close()
  return n
end

-- Byte-for-byte comparison, in chunks.
local function same_content(a, b)
  local fa, fb = io.open(a, "rb"), io.open(b, "rb")
  if not (fa and fb) then
    if fa then fa:close() end
    if fb then fb:close() end
    return false
  end
  local same = true
  while true do
    local x, y = fa:read(1 << 20), fb:read(1 << 20)
    if x ~= y then same = false break end
    if x == nil then break end
  end
  fa:close()
  fb:close()
  return same
end

local function dirname(p) return p:match("^(.*)[/\\][^/\\]*$") or "." end
local function basename(p) return p:match("([^/\\]*)$") end
-- Joined with the separator the folder already uses.
local function join(dir, leaf)
  if dir:match("[/\\]$") then return dir .. leaf end
  local sep = (dir:find("\\", 1, true) and not dir:find("/", 1, true)) and "\\" or "/"
  return dir .. sep .. leaf
end

-- Windows file names (section 6: which also covers macOS and Linux): no
-- control characters or <>:"/\|?*, no trailing dots or spaces, and not a
-- reserved device name.
local RESERVED = {}
for _, n in ipairs({ "CON", "PRN", "AUX", "NUL" }) do RESERVED[n] = true end
for i = 1, 9 do RESERVED["COM" .. i] = true RESERVED["LPT" .. i] = true end

function builder.sanitize(name)
  local s = (name or ""):gsub("[%c<>:\"/\\|%?%*]", "_")
  s = s:gsub("^%s+", ""):gsub("[%s%.]+$", "")
  if s == "" then s = "AAF media" end
  if RESERVED[s:upper()] or RESERVED[(s:match("^([^%.]*)") or ""):upper()] then s = s .. "_" end
  if #s > 180 then s = s:sub(1, 180) end
  return s
end

-- Timecode text for a frame count at a nominal rate. Drop-frame counting
-- skips frame numbers 0 and 1 (2 and 3 at 60) each minute except every
-- tenth.
function builder.timecode_text(frames, fps, drop)
  fps = math.floor(fps + 0.5)
  if fps <= 0 then return tostring(frames) end
  local neg = frames < 0
  if neg then frames = -frames end
  local sep = ":"
  if drop and fps % 30 == 0 then
    local d = fps // 15                         -- frames dropped per minute
    local per_min = fps * 60 - d
    local per_10 = per_min * 10 + d
    local tens, rem = frames // per_10, frames % per_10
    frames = frames + d * 9 * tens
    if rem > d then frames = frames + d * ((rem - d) // per_min) end
    sep = ";"
  end
  local ff = frames % fps
  local s = frames // fps
  return string.format("%s%02d:%02d:%02d%s%02d", neg and "-" or "", s // 3600, (s // 60) % 60, s % 60, sep, ff)
end

-- Seconds as h:mm:ss.mmm, for the report.
local function hms(sec)
  if sec == nil then return "-" end
  local neg = sec < 0
  sec = math.abs(sec)
  local h = math.floor(sec / 3600)
  local m = math.floor(sec / 60) % 60
  local s = sec - h * 3600 - m * 60
  return string.format("%s%d:%02d:%06.3f", neg and "-" or "", h, m, s)
end
builder.hms = hms

