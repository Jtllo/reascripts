-- Source resolution (MS-01 7.7, 6.11): from a clip in a composition down
-- to the file SourceMob whose essence it plays.

local function slot_by_id(mob, id)
  for _, s in ipairs(mob:get("Slots") or {}) do
    if s:get("SlotID") == id then return s end
  end
  return nil
end

-- The segment of a Sequence covering position `p` (rational), and its
-- start (MS-01 7.4: transitions overlap their neighbours).
local function covering(seq, p)
  local pos = 0
  for _, sub in ipairs(seq:get("Components") or {}) do
    local len = sub:get("Length") or 0
    if sub:is_a("Transition") then
      pos = pos - len
    elseif rle(R(pos), p) and rlt(p, R(pos + len)) then
      return sub, pos
    else
      pos = pos + len
    end
  end
  return nil
end

-- Resolve `clip` (owned by a slot at `own_rate`), starting `into` edit
-- units after its StartTime. Returns a source table or nil and a reason.
-- source = { mob, mobid, slot_id, descriptor, rate (file slot edit rate),
--            sample_rate, offset (rational, in samples of sample_rate),
--            channels, media = { kind = "embedded"|"linked"|"none", ... },
--            hops = { { class, mobid, slot_id, rate, origin, at } ... },
--            room (rational seconds from this point to the end of the
--            shortest source segment on the chain, or nil) }
function Context:resolve(clip, own_rate, into)
  local c = clip
  local start = radd(R(c:get("StartTime") or 0), into or R(0))
  local hops = {}
  local room = nil
  local function narrow(len, within, rate)
    local r = rdiv(rsub(R(len), within), rate)
    if not room or rlt(r, room) then room = r end
  end
  for _ = 1, MAX_HOPS do
    local sid = c:get("SourceID")
    if sid == nil or sid == ZERO_MOBID then
      return nil, "clip refers to no source (zero SourceID)", hops
    end
    local m = self.mobs[sid]
    if not m then return nil, "source mob " .. aaf.hex(sid) .. " is not in the file", hops end
    local slot = slot_by_id(m, c:get("SourceMobSlotID"))
    if not slot then
      return nil, string.format("source mob %s has no slot %s", aaf.hex(sid), tostring(c:get("SourceMobSlotID"))), hops
    end
    local ref_rate = rate_of(slot:get("EditRate"))
    if not ref_rate then return nil, "source slot has no edit rate", hops end
    -- MS-01 7.7: StartTime is in the owning slot's edit units; convert it to
    -- the referenced slot's, then MS-01 6.11: add that slot's Origin.
    local p = radd(rmul(start, rdiv(ref_rate, own_rate)), R(slot:get("Origin") or 0))
    local hop = { class = m:class_name(), mobid = sid, slot_id = slot:get("SlotID"), rate = ref_rate,
                  origin = slot:get("Origin") or 0, at = p }
    hops[#hops + 1] = hop

    local desc = m:is_a("SourceMob") and m:get("EssenceDescription") or nil
    if is_object(desc) and desc:is_a("FileDescriptor") then
      -- A file SourceMob (MS-01 6.9): its essence is what plays.
      local sr = rate_of(desc:get("SampleRate")) or ref_rate
      local src = {
        mob = m, mobid = sid, slot_id = slot:get("SlotID"), descriptor = desc,
        rate = ref_rate, sample_rate = sr, offset = rmul(p, rdiv(sr, ref_rate)),
        channels = desc:get("Channels"), hops = hops,
      }
      local ess = self.essence[sid]
      if ess then
        src.media = { kind = "embedded", essence = ess }
      else
        local urls = {}
        for _, loc in ipairs(desc:get("Locator") or {}) do
          if loc:is_a("NetworkLocator") then urls[#urls + 1] = loc:get("URLString") end
        end
        src.media = #urls > 0 and { kind = "linked", urls = urls } or { kind = "none" }
      end
      local seg = slot:get("Segment")
      local seg_len = is_object(seg) and seg:get("Length")
      if seg_len then narrow(seg_len, p, ref_rate) end
      src.room = room
      return src
    end

    -- Otherwise descend to the SourceClip at p and continue down the chain.
    local seg = slot:get("Segment")
    local seg_start = 0
    for _ = 1, MAX_HOPS do
      if not is_object(seg) then break end
      if seg:is_a("Sequence") then
        local sub, at = covering(seg, p)
        if not sub then return nil, string.format("nothing in %s slot %s at %s", m:class_name(), tostring(hop.slot_id), rnum(p)), hops end
        seg, seg_start = sub, seg_start + at
      elseif seg:is_a("Selector") then
        seg = seg:get("Selected")               -- MS-01 7.20
      elseif seg:is_a("EssenceGroup") then
        -- MS-01 7.21: alternative representations of the same essence;
        -- the first choice is taken and noted.
        hop.essence_group = true
        seg = (seg:get("Choices") or {})[1]
      else
        break
      end
    end
    if not (is_object(seg) and seg:is_a("SourceClip")) then
      return nil, string.format("%s slot %s holds %s at the referenced position", m:class_name(),
        tostring(hop.slot_id), is_object(seg) and seg:class_name() or "nothing"), hops
    end
    local within = rsub(p, R(seg_start))
    narrow(seg:get("Length") or 0, within, ref_rate)
    start = radd(R(seg:get("StartTime") or 0), within)
    own_rate = ref_rate
    c = seg
  end
  return nil, "source chain is too long", hops
end

