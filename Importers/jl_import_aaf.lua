-- Locators (brief 4.5): URLs to local paths.

-- Percent-decode a URL component (RFC 2396 escapes) to raw bytes.
local function percent_decode(s)
  return (s:gsub("%%(%x%x)", function(h) return string.char(tonumber(h, 16)) end))
end

-- A NetworkLocator URLString (MS-01 6.21) as a local path. Returns the
-- path and whether it is relative to the AAF's own location. "file" URLs
-- keep their path: /C:/x becomes C:/x; /Volumes/x stays /Volumes/x.
function edit.url_to_path(url)
  local u = url
  local scheme, rest = u:match("^(%a[%w+.-]*):(.*)$")
  if scheme and #scheme == 1 then scheme, rest = nil, nil end  -- a drive letter, not a scheme
  if scheme then
    if scheme:lower() ~= "file" then return nil, false end
    rest = rest:gsub("^//localhost/", "///")
    if rest:sub(1, 3) == "///" then
      rest = rest:sub(3)
    elseif rest:sub(1, 2) == "//" then
      rest = "//" .. rest:sub(3)   -- a UNC host
    end
    local path = percent_decode(rest)
    if path:match("^/%a:[/\\]") or path:match("^/%a:$") then path = path:sub(2) end
    return path, false
  end
  local path = percent_decode(u)
  local absolute = path:match("^%a:[/\\]") or path:match("^[/\\]")
  return path, not absolute
end

