-- Objects

function File:_object(storage, path)
  local o = self._objects[storage.id]
  if o then return o end
  o = setmetatable({ file = self, storage = storage, path = path }, Object)
  self._objects[storage.id] = o
  return o
end

-- The root object (MS-02 1.1: the root storage), the Header and the
-- MetaDictionary.
function File:root()
  return self:_object(self.doc:root(), "")
end

function File:header()
  local r = self:root()
  local e = r:_props().by_pid[PID_ROOT_HEADER]
  if not e then fail("root object has no Header") end
  return r:_resolve(e)
end

-- MS-02 1.2.1.11: resolve a weak reference tag to the strong reference set
-- it names, by following the stored path of pids from the root object.
function File:_referenced_set(tag)
  local cached = self._ref_sets[tag]
  if cached then return cached end
  if not self._ref_paths then
    self._ref_paths = {}
    local st = self.doc:child(self.doc:root(), REFERENCED_PROPERTIES)
    if st then
      local s = self.doc:read_all(st)
      -- MS-02 1.2.1.12 ReferencedPropertiesTableHeader: _byteOrder (1),
      -- _pathCount (2), _pidCount (4); then null-terminated pid lists.
      local bo = BYTE_ORDERS[s:byte(1)] or "<"
      local path_count, pid_count = string.unpack(bo .. "I2I4", s, 2)
      local pos = 8
      local path = {}
      for _ = 1, pid_count do
        local pid = string.unpack(bo .. "I2", s, pos)
        pos = pos + 2
        if pid == 0 then
          table.insert(self._ref_paths, path)
          path = {}
        else
          path[#path + 1] = pid
        end
      end
      if #self._ref_paths ~= path_count then
        fail("referenced properties table has %d paths, header says %d", #self._ref_paths, path_count)
      end
    end
  end
  local path = self._ref_paths[tag + 1]
  if not path then fail("weak reference tag %d is not in the referenced properties table", tag) end
  local obj = self:root()
  for i = 1, #path - 1 do
    obj = obj:get_pid(path[i])
    if type(obj) ~= "table" or getmetatable(obj) ~= Object then
      fail("weak reference path %d does not lead through strong references", tag)
    end
  end
  local set = obj:_set_by_key(path[#path])
  self._ref_sets[tag] = set
  return set
end

function Object:_props()
  return self.file:_read_props(self.storage)
end

function Object:class()
  return self.file.classes[self.storage.clsid]
end

function Object:class_name()
  local c = self:class()
  return c and c.name or ("class " .. aaf.auid_string(self.storage.clsid))
end

-- True if this object's class is `name` or descends from it.
function Object:is_a(name)
  for _, c in ipairs(self.file:class_chain(self:class())) do
    if c.name == name then return true end
  end
  return false
end

-- The property definition for `name` on this object's class chain.
function Object:prop_def(name)
  for _, c in ipairs(self.file:class_chain(self:class())) do
    local d = c.props_by_name[name]
    if d then return d end
  end
  return nil
end

function Object:has(name)
  local d = self:prop_def(name)
  return d ~= nil and self:_props().by_pid[d.pid] ~= nil
end

-- Resolve a stored property entry to a Lua value.
function Object:_resolve(e)
  local p = self:_props()
  local bo = p.bo
  local sf = e.sf
  local f = self.file
  if sf == SF_STRONG_OBJECT_REFERENCE then
    local name = flat_name(e, bo)
    local st = f.doc:child(self.storage, name)
    if not st then fail("'%s' refers to missing storage '%s'", self.path, name) end
    return f:_object(st, self.path .. "/" .. name)
  end
  if sf == SF_STRONG_OBJECT_REFERENCE_VECTOR then
    local name = flat_name(e, bo)
    local out = {}
    for i, key in ipairs(f:_vector_index(self.storage, name, bo)) do
      local en = element_name(name, key)
      local st = f.doc:child(self.storage, en)
      if not st then fail("vector element '%s/%s' is missing", self.path, en) end
      out[i] = f:_object(st, self.path .. "/" .. en)
    end
    return out
  end
  if sf == SF_STRONG_OBJECT_REFERENCE_SET then
    local name = flat_name(e, bo)
    local out = {}
    for i, c in ipairs(f:_set_children(self.storage, e, bo)) do
      out[i] = f:_object(c.storage, self.path .. "/" .. c.storage.name)
    end
    return out
  end
  if sf == SF_WEAK_OBJECT_REFERENCE then
    local r = parse_weak(e.value, bo)
    return f:_referenced_set(r.tag)[r.key] or { unresolved = r.key }
  end
  if sf == SF_WEAK_OBJECT_REFERENCE_VECTOR or sf == SF_WEAK_OBJECT_REFERENCE_SET then
    local out = {}
    for i, r in ipairs(f:_weak_index(self.storage, flat_name(e, bo), bo)) do
      out[i] = f:_referenced_set(r.tag)[r.key] or { unresolved = r.key }
    end
    return out
  end
  if sf == SF_DATA_STREAM then
    local name = flat_name(e, bo)
    local st = f.doc:child(self.storage, name)
    if not st then fail("'%s' refers to missing stream '%s'", self.path, name) end
    -- MS-02 1.4.3: the flat value starts with the stream data's byte order.
    return { stream = st, byte_order = BYTE_ORDERS[e.value:byte(1)] or bo }
  end
  if sf == SF_DATA then
    local d = f.props_by_pid[e.pid]
    local t = d and f.types[d.type_id]
    if not t then return { raw = e.value } end
    return f:decode(t, e.value, bo)
  end
  -- MS-02 1.4.2.2: consumers must skip stored forms they don't understand.
  return { raw = e.value, stored_form = sf }
end

-- key -> object map of a strong reference set property, keyed by each
-- element's identification (MS-02 1.2.1.6.4).
function Object:_set_by_key(pid)
  local p = self:_props()
  local e = p.by_pid[pid]
  if not e or e.sf ~= SF_STRONG_OBJECT_REFERENCE_SET then
    fail("'%s' property 0x%04x is not a strong reference set", self.path, pid)
  end
  local out = {}
  for _, c in ipairs(self.file:_set_children(self.storage, e, p.bo)) do
    out[auid_key(c.id, p.bo)] = self.file:_object(c.storage, self.path .. "/" .. c.storage.name)
  end
  return out
end

-- Value of the property with local id `pid`, or nil if absent.
function Object:get_pid(pid)
  local e = self:_props().by_pid[pid]
  if not e then return nil end
  return self:_resolve(e)
end

-- Value of the property called `name`, or nil if the class has no such
-- property or this object doesn't carry it.
function Object:get(name)
  local d = self:prop_def(name)
  if not d then return nil end
  return self:get_pid(d.pid)
end

-- Flat bytes of a property, and the byte order they are in.
function Object:raw(name)
  local d = self:prop_def(name)
  local e = d and self:_props().by_pid[d.pid]
  if not e then return nil end
  return e.value, self:_props().bo, e.sf
end

-- Every stored property: { pid, sf, name (or nil), def (or nil) } in stored
-- order. Properties whose pid the dictionary doesn't define have no name.
function Object:properties()
  local out = {}
  for _, e in ipairs(self:_props().list) do
    local d = self.file.props_by_pid[e.pid]
    out[#out + 1] = { pid = e.pid, sf = e.sf, name = d and d.name, def = d, entry = e }
  end
  return out
end

function Object:value_of(prop)
  return self:_resolve(prop.entry)
end

